/**
 * What `railway up` uploads. It follows `.gitignore`, and only inside a git repository, so a project without one would
 * upload its credentials, and one with one would drop `.fastagent/deploy/`, which `.gitignore` ignores and the image is
 * built from. `.railwayignore` outranks `.gitignore`; a parent that is ignored hides its children, hence the three
 * lines for the one directory (verified against Railway, which reads the same patterns as ripgrep).
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import ignore from "ignore";
import { DELIVERED_CONFIG_DIR } from "../container.ts";

export const RAILWAYIGNORE_FILE = ".railwayignore";
const MARKER = "# Generated by `fastagent deploy railway`";

export function isGeneratedRailwayignore(content: string): boolean {
  return content.startsWith(MARKER);
}

export function railwayignore(): string {
  return `${MARKER}. Delete this line to take ownership (deploy then keeps your file).
# Credentials, state and clones never leave this machine, whatever .gitignore says.
.secrets
.state
/content
.env
.env.*
!.env.example
# The deploy's own directory is what the image is built from, and .gitignore ignores .fastagent.
!.fastagent
.fastagent/*
!${DELIVERED_CONFIG_DIR}
`;
}

function readIfExists(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return "";
    throw error;
  }
}

/**
 * Why a `.railwayignore` the author kept would leave the deploy's own directory out of the upload, so the image build
 * could not copy it, or undefined when it lets it through (or there is none to keep).
 */
export function keptRailwayignoreProblem(agentDir: string): string | undefined {
  const kept = readIfExists(join(agentDir, RAILWAYIGNORE_FILE));
  if (kept === "" || isGeneratedRailwayignore(kept)) return undefined;
  const upload = ignore()
    .add(readIfExists(join(agentDir, ".gitignore")))
    .add(kept);
  if (!upload.ignores(`${DELIVERED_CONFIG_DIR}/fastagent.json`)) return undefined;
  return (
    `your ${RAILWAYIGNORE_FILE} (kept), with .gitignore, leaves ${DELIVERED_CONFIG_DIR}/ out of what \`railway up\` ` +
    `uploads, and the image is built from it. Add \`!.fastagent\`, \`.fastagent/*\` and \`!${DELIVERED_CONFIG_DIR}\` ` +
    `to it, or delete it to let deploy generate one.`
  );
}
