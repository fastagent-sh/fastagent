/** `fastagent deploy docker` — the local-Docker plan. */
import { basename } from "node:path";
import type { DeclaredChannel } from "../../channels/discover.ts";
import { webhookPaths } from "../channel-ingress.ts";
import { manualWebhookStep, webhookKinds } from "../../channels/webhooks.ts";
import { type Artifact, type ContainerInput, containerArtifacts, redeployCommand } from "../container.ts";
import { deliveredVariables } from "../delivery.ts";
import { deploymentLoginCommand } from "../box-shell.ts";
import type { DeploymentSecret } from "../secrets.ts";
import { SECRETS_DIRNAME } from "../../paths.ts";
import { stripEdges, stripEnd } from "../../strip-edges.ts";

export interface DockerPlanInput extends ContainerInput {
  /** Stable Compose project name, sanitized by {@link toDockerProjectName}. */
  projectName: string;
  /** Container + default host port. */
  port: number;
  /**
   * The provider the deployment logs in to itself (`fastagent login --deployment`): its credential is not a variable
   * the plan carries.
   */
  boxLogin?: string;
  /** Every declared channel and its ingress — the source of the ingress note. */
  channels: readonly DeclaredChannel[];
  /**
   * The runbook's variable list (`deploymentSecrets`): the declared names, each hinted by the file that declared it.
   */
  secrets?: readonly DeploymentSecret[];
  /** The value file as the pre-flight resolved it (it follows `FASTAGENT_SECRETS_DIR`), agent-dir-relative. */
  valueFile: string;
}

export interface DockerPlan {
  /** The instance's Compose file + the shared Dockerfile/ignore artifacts. */
  artifacts: Artifact[];
  /** Compose file path relative to the agent directory. */
  composePath: string;
  /** Ordered local build/run/operate instructions. */
  runbook: string[];
}

const MOUNT = "/data";
/** The instance's Compose file: `fastagent.<name>.compose.yml`, in the agent directory. */
export const dockerComposeFile = (name: string): string => `fastagent.${name}.compose.yml`;

/** Is `path` a Compose file this host names (`dockerComposeFile`)? */
export const isDockerComposePath = (path: string): boolean =>
  /^fastagent\.[A-Za-z0-9_-]+\.compose\.yml$/.test(basename(path));
export const DOCKER_VALUE_FILE = `${SECRETS_DIRNAME}/production/.env`;
const GENERATED_COMPOSE_MARKER = "# Generated by `fastagent deploy docker`";
export const MIN_DOCKER_COMPOSE_VERSION = "2.3.3";
/** Whether a Compose file still opts into generated-drift warnings (drop the marker after taking ownership). */
export function isGeneratedCompose(content: string): boolean {
  return content.startsWith(GENERATED_COMPOSE_MARKER);
}

/** Compose project names are lowercase [a-z0-9_-] and must start with an alphanumeric character. */
export function toDockerProjectName(name: string): string {
  const separator = (char: string) => char === "-" || char === "_";
  const slug = stripEnd(
    stripEdges(name.toLowerCase().replace(/[^a-z0-9_-]+/g, "-"), separator).slice(0, 54),
    separator,
  );
  return `fastagent-${slug || "agent"}`;
}

/** A value as a Compose scalar: JSON's string is a YAML one, and Compose reads `$` as interpolation, so each is doubled. */
const composeScalar = (value: string): string => JSON.stringify(value).replaceAll("$", () => "$$");

function composeYaml(input: DockerPlanInput): string {
  const variables = Object.entries(deliveredVariables(input))
    .map(([name, value]) => `      ${name}: ${composeScalar(value)}`)
    .join("\n");
  return `${GENERATED_COMPOSE_MARKER}. Edit freely — it is kept unless you pass --force.
# Public ingress remains yours: add your own tunnel/proxy/DNS/TLS, and name its URL as http.publicUrl.
name: ${input.projectName}

services:
  agent:
    build:
      context: .
      dockerfile: Dockerfile
    ports:
      - "127.0.0.1:${input.port}:${input.port}"
    # The deployed environment's own declaration, read by the container itself. \`env_file\`, not per-name
    # \${NAME:-} interpolation: interpolation resolves from the SHELL or the project .env, which is exactly the
    # source a deployment must not have. A FIXED path, never the builder's FASTAGENT_SECRETS_DIR — this file is a
    # committed artifact and must mean the same thing on every machine. \`deploy\` creates it if it is missing.
    env_file:
      - ${DOCKER_VALUE_FILE}
    environment:
      PORT: "${input.port}"
      # What varies per instance, rendered here: its name, its release and its configuration (a \`$\` is written \`$$\`).
${variables}
      # Machinery on the ONE state volume: mutable state and credentials (logged in on the box); the agent's content
      # is linked there by the release itself. Pinned AFTER env_file so a local path in that file (the scaffold lists
      # these) cannot send the container's state, sessions or credentials somewhere outside the volume — or at a
      # host path that does not exist here at all.
      FASTAGENT_STATE_DIR: "${MOUNT}/.state"
      FASTAGENT_SECRETS_DIR: "${MOUNT}/.secrets"
      FASTAGENT_AUTH_PATH: "${MOUNT}/.secrets/auth.json"
    volumes:
      - state:${MOUNT}
    # The agent's log is where a failure's reason is recorded (a scheduled fire logs the detail; what the turn
    # SAID is in its session, not here), and Docker's default json-file driver never rotates — so on this host
    # the bound has to be written down. Fly and Railway bound their own log retention; AgentCore does NOT
    # (CloudWatch keeps data indefinitely until an operator sets a retention policy — its runbook says so).
    logging:
      driver: json-file
      options:
        max-size: "10m"
        max-file: "3"
    restart: unless-stopped

volumes:
  state:
`;
}

/**
 * What `--run` says of the webhook channels once Compose is up. Docker has no URL of its own: with `http.publicUrl`
 * named in the delivered configuration the agent points its own channels there (its `/health` says how each went) and
 * only Slack's Request URL is the operator's; without one, nothing can reach those paths yet.
 */
export function ingressNotes(
  channels: readonly DeclaredChannel[],
  publicUrl: string | undefined,
  healthUrl: string | undefined,
): string[] {
  const paths = webhookPaths(channels);
  if (paths.length === 0) return [];
  if (publicUrl === undefined) {
    return [
      `${paths.join(", ")} receive nothing until a public URL reaches this container — configure your own ` +
        `tunnel/proxy, point those webhook path(s) (or your remapped channel routes) at it and name its URL as ` +
        `http.publicUrl in the configuration --config delivers, or set the channel's ingress to "connection" ` +
        `where it has one`,
    ];
  }
  return [
    `the agent points its webhook channels at ${publicUrl} on every start; ${healthUrl ?? "its /health"} says how each went`,
    ...(webhookKinds(channels).includes("slack") ? [manualWebhookStep("slack", publicUrl)] : []),
  ];
}

/** Compute local-Docker artifacts + the runbook; no Docker process is touched here. */
export function planDockerDeploy(input: DockerPlanInput): DockerPlan {
  const composePath = dockerComposeFile(input.agent);
  const artifacts: Artifact[] = [{ path: composePath, content: composeYaml(input) }, ...containerArtifacts(input)];
  // One spelling for every command: the generated file names the value file itself (`env_file`), so no command
  // needs a flag to reach the deployed environment's declaration.
  const compose = `docker compose -f ${composePath}`;
  const secrets = input.secrets ?? [];
  const paths = webhookPaths(input.channels);

  const runbook: string[] = [
    `# Run FastAgent in local Docker. ${composePath} / Dockerfile(.dockerignore) are generated above.`,
    `# Existing artifacts are authoritative and kept; edit Dockerfile or ${composePath} freely.`,
    `# Prereqs: Docker Engine/Desktop with Compose >= ${MIN_DOCKER_COMPOSE_VERSION} (\`docker compose version\`).`,
  ];

  if (secrets.length > 0) {
    runbook.push(
      `# Environment: the container reads ${input.valueFile} whole (Compose \`env_file\`) — that file declares the`,
      `# deployed environment (in CI, write it before running the command):`,
      ...secrets.map((secret) => `#   ${secret.name}: ${secret.hint}`),
    );
  }
  runbook.push(
    `# Run from the agent directory. The build bakes it as the definition and installs its`,
    `# package.json dependencies.`,
  );

  runbook.push(
    ``,
    `# After a change to the configuration, run \`${redeployCommand("docker", input, true)}\`: ${composePath} carries it, and`,
    `# --force resets it to the generated file (re-apply hand edits).`,
    `# The Compose volume at ${MOUNT} is the agent's working directory, and retains its state and credentials.`,
    `# --pull: the base image is a floating tag, and a copy cached here may be older than the runtime floor.`,
    `${compose} build --pull`,
    `${compose} up -d`,
    `curl --fail http://127.0.0.1:${input.port}/health`,
    ...(input.boxLogin
      ? [
          `# Model auth: once it is up, the deployment logs in to ${input.boxLogin} itself:`,
          `${deploymentLoginCommand("docker", input.boxLogin, input.configFile)}`,
        ]
      : []),
    ``,
    `# Operate it:`,
    `${compose} logs -f agent`,
    `${compose} ps`,
    `${compose} down        # stops containers; keeps the state volume`,
    `# ${compose} down -v   # DESTRUCTIVE: deletes credentials and all agent state`,
  );

  if (paths.length > 0) {
    runbook.push(
      ``,
      `# Public ingress is operator-owned: add your tunnel/proxy/DNS/TLS, then route the detected default`,
      `# endpoint(s) to the agent: ${paths.map((path) => `https://<your-domain>${path}`).join(", ")}.`,
      `# If your channels/*.ts glue remaps a route, use that path instead. Name that URL as http.publicUrl in the`,
      `# configuration \`--config\` delivers, and the agent points Telegram and Feishu/Lark at it on every start`,
      `# (Slack's Request URL stays yours to set).`,
    );
  }

  runbook.push(
    `# Keep one agent replica: the local state volume is single-process; multiple replicas split/corrupt state.`,
  );

  return { artifacts, composePath, runbook };
}
