/** The portable container — Dockerfile + .dockerignore, host-neutral. */
import { CONTENT_DIRNAME, INSTANCE_CONFIG_FILE, INSTANCES_DIRNAME, SECRETS_DIRNAME, STATE_DIRNAME } from "../paths.ts";
import { RUNTIME_FLOOR } from "../runtime.ts";
import { MISE_ENVIRONMENT } from "../environment/mise.ts";
import { BOX_CLI_PREDATES } from "./box-shell.ts";

/**
 * What a deploy writes for the image beyond the program: the package list. FastAgent's own directory, so it is ignored
 * by git and absent from the author's root. It holds the program's, so every instance's image is the same one.
 */
export const DEPLOY_DIR = `${INSTANCES_DIRNAME}/deploy`;

/**
 * The packages the image installs, one per line as mise is given them: build output every deploy writes, so the layer
 * that installs them is built again when they change and not when anything else does.
 */
export const PACKAGES_PATH = `${DEPLOY_DIR}/fastagent.packages`;

/** What every deploy writes whoever wrote it before: build output, by its path, never kept or reported stale. */
export const BUILD_OUTPUTS: readonly string[] = [PACKAGES_PATH];

export interface Artifact {
  path: string;
  content: string;
}

/**
 * The result line for a box CLI that refused this CLI's `login --stdio` as a usage error: an option it does not know
 * (`--stdio` itself, or one added since, such as `--method`). See {@link boxLoginCommand}.
 */
const STDIO_PREDATED = JSON.stringify({
  type: "result",
  ok: false,
  reason: "failed",
  message: BOX_CLI_PREDATES,
}).replaceAll('"', '\\"');

/** Where a generated image keeps its storage (`FASTAGENT_ROOT`); every host mounts its volume here. */
const STORAGE_DIR = "/data";

/** Where a generated image holds the agent: the build context, which is the agent directory. */
export const IMAGE_APP_DIR = "/app";

/**
 * The shell command that runs `fastagent login --stdio <args>` inside a running generated image, as the server there
 * would see it: in the image's agent directory, with the storage and credential paths resolved by the same defaults
 * `prepareStartWorkspace` applies. A host's own shell does not reliably hand those over — its session may not start
 * in the server's directory, and the platform's variables are the only ones it inherits. `storage` names the root
 * outright for a shell that inherits none of them; `program` is where the image has the agent, the generated one's
 * by default. The CLI is the one the server runs: the agent's own install when
 * it has one (under Bun when the image is Bun's), else the pinned global.
 *
 * That own install may predate `login --stdio` (an agent pinned to an older release, deployed by a newer CLI). It then
 * refuses the flag as a usage error, exit 2, which a `login --stdio` that ran never gives (it answers 0 or 1 after its
 * result line), so the command answers for it: one result line naming the mismatch, instead of a shell that ended
 * with nothing to say. No quote or backtick in it: hosts wrap this whole line in `sh -c '…'`.
 */
export function boxLoginCommand(
  args: readonly string[],
  { storage, program = IMAGE_APP_DIR }: { storage?: string; program?: string } = {},
): string {
  for (const value of [...args, ...(storage ? [storage] : []), program]) {
    if (!/^[\w.@/-]+$/.test(value)) throw new Error(`cannot pass ${JSON.stringify(value)} to a shell on the box`);
  }
  return [
    ...(storage
      ? [`root="${storage}"`, `export FASTAGENT_SECRETS_DIR="$root/.secrets"`]
      : [
          `root="\${FASTAGENT_ROOT:-${STORAGE_DIR}}"`,
          `export FASTAGENT_SECRETS_DIR="\${FASTAGENT_SECRETS_DIR:-$root/.secrets}"`,
        ]),
    `cd "${program}" || exit 1`,
    `f=fastagent`,
    `if [ -x node_modules/.bin/fastagent ]; then f=node_modules/.bin/fastagent; if command -v bun >/dev/null; then f="bun run fastagent"; fi; fi`,
    `$f login --stdio ${args.join(" ")}`,
    `code=$?`,
    `if [ $code -eq 2 ]; then printf "%s\\n" "${STDIO_PREDATED}"; fi`,
    `exit $code`,
  ].join("; ");
}

/** Fixed first-line prefix of a fastagent-generated Dockerfile. */
export const GENERATED_DOCKERFILE_MARKER = "# Generated by `fastagent deploy`";

/** The ONE predicate for "did fastagent generate this Dockerfile?". */
export function isGeneratedDockerfile(content: string): boolean {
  return content.startsWith(GENERATED_DOCKERFILE_MARKER);
}

/** First line of a generated `.dockerignore`. */
const GENERATED_DOCKERIGNORE_MARKER = "# Generated by `fastagent deploy`";

export function isGeneratedDockerignore(content: string): boolean {
  return content.startsWith(GENERATED_DOCKERIGNORE_MARKER);
}

export interface ContainerInput {
  /** The package manager the generated image targets. */
  runtime: "node" | "bun";
  /** Whether the runtime's lockfile exists (package-lock.json for npm, bun.lock/bun.lockb for bun). */
  hasLockfile: boolean;
  /** For `runtime: "bun"`, the `FROM oven/bun:<tag>` version (from packageManager `bun@x`), else `"1"`. */
  bunVersion?: string;
  /**
   * The Debian packages the image installs: what FastAgent needs (git for content and a shipped `.git`, CA certificates
   * and curl for mise), then the agent's `aptPackages`.
   */
  apt?: string[];
  /** The packages the agent declares, as mise is given them (`gh@2`): the image installs them with the agent's own mise. */
  packages?: string[];
  /**
   * The configuration the deployment delivers as one line of JSON (`deliveredConfig`), set on the box as
   * `FASTAGENT_CONFIG_JSON`: the host renders it with the instance's other variables, and the image holds none of it.
   */
  config: string;
  /** The instance's name, set on the box as `FASTAGENT_NAME`: the agent its storage belongs to. */
  agent: string;
  /** The `--config` file that names the instance, in the commands a runbook prints. */
  configFile?: string;
  /** Agent-dir-relative machinery paths the NAME-based excludes below would miss. */
  machineryPaths?: string[];
  /** Whether the agent directory ships a `.git` (preflight fact). */
  shipsGit?: boolean;
}

/** Whether the image has git: FastAgent installs it for its own needs, or the agent declares it in `aptPackages`. */
export function imageHasGit(input: Pick<ContainerInput, "apt">): boolean {
  return input.apt?.includes("git") === true;
}

/** The apt layer (cached right after FROM). */
function aptLayer(packages?: string[]): string {
  return packages && packages.length > 0
    ? `RUN apt-get update \\
 && apt-get install -y --no-install-recommends ${packages.join(" ")} \\
 && rm -rf /var/lib/apt/lists/*
`
    : "";
}

/** mise's own directories for the build, thrown away with the layer: nothing of them is read at run time. */
const BUILD_MISE_DIR = "/tmp/mise";

/** Where the build holds the package list while it installs them: not the program's directory. */
const BUILD_PACKAGES = "/tmp/fastagent.packages";

/**
 * The layer that installs the agent's packages, after its dependencies (the agent's own mise among them) and before the
 * definition, so it stays cached while the definition changes. It reads them from {@link PACKAGES_PATH}, which deploy
 * writes, rather than listing them: the Dockerfile is kept once written, and a list here would make every package
 * change one that `--run` stops on. The packages go to mise's system directory (`--system`,
 * /usr/local/share/mise/installs), which every mise reads beside its own data directory, so a start installs nothing.
 */
function environmentLayer(dir: string): string {
  const isolation = Object.entries(MISE_ENVIRONMENT)
    .map(([key, value]) => `${key}=${value}`)
    .join(" ");
  // The agent's own mise, by its package: the bin link is not reliable (mise.ts `miseBinary`).
  const mise = `${dir}/node_modules/@jdxcode/mise-linux-$(case "$(uname -m)" in aarch64|arm64) echo arm64;; *) echo x64;; esac)/bin/mise`;
  const steps = [
    `export ${isolation} MISE_DATA_DIR=${BUILD_MISE_DIR} MISE_CACHE_DIR=${BUILD_MISE_DIR}/cache MISE_STATE_DIR=${BUILD_MISE_DIR}/state MISE="${mise}"`,
    // One argument per line, read as it is: no quote or backslash in a package means anything to xargs.
    `xargs -d '\\n' -a ${BUILD_PACKAGES} "$MISE" install --system`,
    `rm -rf ${BUILD_MISE_DIR}`,
  ];
  return `COPY ${PACKAGES_PATH} ${BUILD_PACKAGES}
RUN ${steps.join(" \\\n && ")}
`;
}

/**
 * The Node image an npm-based agent runs on: the newest of the floor's line. A floating tag, so every build pulls it
 * (docker/run.ts, agentcore/run.ts): a copy cached before the floor's release would start a Node the CLI refuses.
 */
export const NODE_IMAGE = `node:${RUNTIME_FLOOR.node.split(".")[0]}-slim`;

/** Why the image builds `dist/` itself: an upload that follows `.gitignore` (`railway up`) drops it, and `start` needs it. */
const BUILD_STEP_NOTE = "# `start` opens dist/, which an upload that follows .gitignore leaves out: build it here.";

function dockerfile(input: ContainerInput): string {
  // The build context is the agent directory, baked at IMAGE_APP_DIR; deps install (and the local bin lives)
  // there.
  const dir = IMAGE_APP_DIR;
  const layoutNote = `The agent directory is baked at ${dir}`;
  // apt layer right after FROM (cached across code changes): the agent's tools may shell out to git etc., which the
  // slim image lacks.
  const apt = aptLayer(input.apt);
  // The caches stay off the volume: they are rebuildable, and a host mount is the slow disk.
  const deployment = `ENV FASTAGENT_ROOT=${STORAGE_DIR}\nENV npm_config_cache=/tmp/fastagent/npm\nENV BUN_INSTALL_CACHE_DIR=/tmp/fastagent/bun\n`;
  const environment = input.packages && input.packages.length > 0 ? environmentLayer(dir) : "";
  const isBun = input.runtime === "bun";
  const base = isBun ? `oven/bun:${input.bunVersion ?? "1"}` : NODE_IMAGE;
  const note = isBun
    ? "# Bun-based (packageManager: bun / a bun lockfile detected). fastagent runs under Bun (bun run)."
    : "# npm-based — for pnpm/yarn, adapt the install line + the lockfile COPY (corepack enable, etc.).";
  const head = `${GENERATED_DOCKERFILE_MARKER}. ${layoutNote}
${note}
FROM ${base}
${apt}WORKDIR ${dir}
${deployment}`;
  // Install ALL deps (no --omit=dev / --production): an agent's tools may need its full toolchain.
  //
  // `*.tgz` RIDES ALONG with the manifest, because the install layer runs BEFORE `COPY . .` and a
  // `"dep": "file:./something.tgz"` resolves against the directory it is installing in. Without this the file is
  // not there yet and the build fails on a dependency the author can see sitting in the agent directory.
  if (isBun) {
    // `--frozen-lockfile` needs bun.lock and hard-fails without it.
    const install = input.hasLockfile ? "bun install --frozen-lockfile" : "bun install";
    return `${head}COPY package.json bun.lock* *.tgz ./
RUN ${install}
${environment}COPY . .
${BUILD_STEP_NOTE}
RUN bun run fastagent build
CMD ["bun", "run", "fastagent", "start", "${dir}"]
`;
  }
  // `npm ci` requires a lockfile and hard-fails without one (a common `init --no-install` agent); fall back to `npm
  // install` when there is none so the build never breaks.
  const install = input.hasLockfile ? "npm ci" : "npm install";
  return `${head}COPY package.json package-lock.json* *.tgz ./
RUN ${install}
${environment}COPY . .
${BUILD_STEP_NOTE}
RUN ./node_modules/.bin/fastagent build
CMD ["./node_modules/.bin/fastagent", "start", "${dir}"]
`;
}

/** Patterns are RECURSIVE (`**​/`) on purpose. */
const dockerignore = (input: ContainerInput): string =>
  DOCKERIGNORE_BASE +
  (input.machineryPaths ?? [])
    // Skip what the name-based rules above already cover: the default `.secrets` / `.state` and anything inside them.
    .filter((p) => [SECRETS_DIRNAME, STATE_DIRNAME].every((covered) => p !== covered && !p.startsWith(`${covered}/`)))
    .map(
      (p) => `# resolved machinery path (FASTAGENT_SECRETS_DIR / FASTAGENT_AUTH_PATH / FASTAGENT_STATE_DIR)\n/${p}\n`,
    )
    .join("");

const DOCKERIGNORE_BASE = `${GENERATED_DOCKERIGNORE_MARKER}. Delete this line to take ownership (deploy then keeps your file).
**/node_modules
**/${SECRETS_DIRNAME}/**
**/${STATE_DIRNAME}
/${INSTANCES_DIRNAME}
# what a deploy writes for the image: the package list
!/${DEPLOY_DIR}
/${CONTENT_DIRNAME}
# the project's own instance configuration: the development instance's, which a deploy does not carry
/${INSTANCE_CONFIG_FILE}
**/.cache
**/.env
**/.env.*
!**/.env.example
!**/${SECRETS_DIRNAME}/.gitignore
**/*.log
# .git is deliberately shipped with the definition (the generated image installs the git binary
# when this directory ships a .git; otherwise run "fastagent env add apt:git"). For a smaller image with no
# git needs, add a ".git" line here.
`;

/** The Dockerfile + ignore artifacts — spread into any host's artifact list. */
export function containerArtifacts(input: ContainerInput): Artifact[] {
  return [
    // Written without packages too, empty: a list an earlier deploy left would otherwise outlive the last package.
    { path: PACKAGES_PATH, content: (input.packages ?? []).map((spec) => `${spec}\n`).join("") },
    { path: "Dockerfile", content: dockerfile(input) },
    { path: ".dockerignore", content: dockerignore(input) },
  ];
}
