/**
 * The generated registry (architecture.md §3): `.fastagent/registry.ts`, plain imports of every module in `src/tools/`,
 * `src/extensions/`, `src/channels/` and `src/schedules/`, so nothing is imported by hand, types flow and a bundler can
 * follow it. Each module default-exports one thing; a file directly in the directory is a module, and anything else a
 * module imports (a helper) lives outside these directories. Generated from the files, never edited.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

export const REGISTRY_KINDS = ["tools", "extensions", "channels", "schedules"] as const;
type RegistryKind = (typeof REGISTRY_KINDS)[number];

/** One module of the definition: where it is, and what it default-exports. */
interface RegisteredModule {
  /** Relative to the agent directory, as the author opens it: `src/tools/weather.ts`. */
  file: string;
  /** The file's name without its extension: a schedule's name. */
  name: string;
  value: unknown;
}

export type Registry = Record<RegistryKind, readonly RegisteredModule[]>;

export const GENERATED_DIR = ".fastagent";
export const REGISTRY_FILE = "registry.ts";

const MODULE = /^([^.][^/]*)\.(ts|mts|js|mjs)$/;
const NOT_A_MODULE = /\.(d|test|spec)\.[a-z]+$/;

/** The module files of one directory of `src/`, sorted so the registry is the same wherever it is generated. */
async function modulesIn(dir: string, kind: RegistryKind): Promise<{ file: string; name: string }[]> {
  let names: string[];
  try {
    names = await readdir(join(dir, "src", kind));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  }
  return names.sort().flatMap((entry) => {
    const match = MODULE.exec(entry);
    return match === null || NOT_A_MODULE.test(entry)
      ? []
      : [{ file: `src/${kind}/${entry}`, name: match[1] as string }];
  });
}

/** The registry's source: one default import per module, grouped by directory. */
export async function registrySource(dir: string): Promise<string> {
  const lines = ["// Generated by fastagent from src/: do not edit.", ""];
  const groups: string[] = [];
  let index = 0;
  for (const kind of REGISTRY_KINDS) {
    const entries: string[] = [];
    for (const { file, name } of await modulesIn(dir, kind)) {
      const local = `m${index++}`;
      lines.push(`import ${local} from ${JSON.stringify(`../${file}`)};`);
      entries.push(`  { file: ${JSON.stringify(file)}, name: ${JSON.stringify(name)}, value: ${local} },`);
    }
    groups.push(`export const ${kind} = [\n${entries.join("\n")}${entries.length > 0 ? "\n" : ""}];`);
  }
  return `${lines.join("\n")}${index > 0 ? "\n" : ""}\n${groups.join("\n\n")}\n`;
}

/** Write `.fastagent/registry.ts` for the agent in `dir`, and return its path. */
export async function generateRegistry(dir: string): Promise<string> {
  const path = join(dir, GENERATED_DIR, REGISTRY_FILE);
  await mkdir(join(dir, GENERATED_DIR), { recursive: true });
  await writeFile(path, await registrySource(dir));
  return path;
}
