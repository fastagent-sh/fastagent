interface PlannedWrite {
  rel: string;
  content: string;
  mode: "create" | "update";
  previous?: string;
}

export interface ScaffoldResult {
  /** The agent directory: `dir` itself. */
  dir: string;
  /** Whether this run scaffolded a fresh directory or adopted/resumed an existing agent directory. */
  mode: "fresh" | "existing";
  /** Files created by this run (relative to `dir`). */
  created: string[];
  /** Existing files updated in place by this run (relative to `dir`). */
  updated: string[];
  /** Existing author or setup files preserved untouched by this run (relative to `dir`). */
  preserved: string[];
  /** True when `package.json` was created or required dependency declarations were added. */
  dependenciesChanged: boolean;
  /** Credentials already tracked in Git (cannot be protected by `.gitignore` without untracking). */
  trackedSecrets: string[];
  /** Remove or restore what this run wrote, for a caller whose next step failed. */
  undo(): Promise<void>;
}

/** Entries a directory may hold and still count as empty. */
const IGNORABLE = [".DS_Store", ".gitkeep", ".keep"];

/** FastAgent build entry marker emitted by `harnesses/build.ts`. */
const FASTAGENT_BUILD_MARKER = "// Generated by fastagent build:";

const CHILD_HINT = "fastagent init agents/support";

const ROOT_IGNORE_RULES: readonly { probe: string; rule: string }[] = [
  { probe: "node_modules/pkg", rule: "node_modules" },
  { probe: "dist/index.js", rule: "/dist" },
  { probe: ".fastagent/dev/agent.sqlite", rule: ".fastagent" },
  { probe: ".state/agent.sqlite", rule: ".state" },
  { probe: ".cache/entry", rule: ".cache" },
  { probe: ".env", rule: ".env" },
  { probe: ".env.local", rule: ".env.*" },
];

const SEMVER_SPEC = /^(\^|~)?(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z.-]+)?$/;

async function lstatOrMissing(path: string) {
  return lstat(path).catch((e: NodeJS.ErrnoException) => {
    if (e.code === "ENOENT" || e.code === "ENOTDIR") return undefined;
    throw e;
  });
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Reject symlinks or type mismatches anywhere along `rel` inside `dir` before writing. */
export async function assertSafeWriteTarget(dir: string, rel: string, mode: "create" | "update"): Promise<void> {
  const parts = rel.split(/[\\/]/).filter(Boolean);
  let cursor = dir;
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i] as string;
    const partial = parts.slice(0, i + 1).join("/");
    cursor = join(cursor, part);
    const st = await lstatOrMissing(cursor);
    if (st === undefined) break;
    if (st.isSymbolicLink()) {
      throw new Error(`refusing to write through symlink "${partial}" in ${dir}`);
    }
    const isLeaf = i === parts.length - 1;
    if (!isLeaf && !st.isDirectory()) {
      throw new Error(`cannot write "${rel}": "${partial}" exists and is not a directory`);
    }
    if (isLeaf && !st.isFile()) {
      throw new Error(`cannot write "${rel}": it exists and is not a file`);
    }
    if (isLeaf && mode === "create") {
      throw new Error(`cannot create "${rel}": file already exists`);
    }
  }
}

/** Recognize actual agent assets (never `AGENTS.md` alone, which host repositories commonly hold). */
async function hasAgentAssets(dir: string): Promise<boolean> {
  const checks: Array<{ path: string; kind: "file" | "dir" }> = [
    { path: AGENT_CONFIG_FILE, kind: "file" },
    { path: "SYSTEM.md", kind: "file" },
    ...MCP_CONFIG_FILES.map((path) => ({ path, kind: "file" as const })),
    { path: "skills", kind: "dir" },
    { path: "prompts", kind: "dir" },
    { path: join("src", "tools"), kind: "dir" },
  ];
  for (const check of checks) {
    const st = await lstatOrMissing(join(dir, check.path));
    if (st === undefined || st.isSymbolicLink()) continue;
    if (check.kind === "file" && st.isFile()) return true;
    if (check.kind === "dir" && st.isDirectory()) return true;
  }
  return false;
}

/** Whether `dir` contains `.js` files outside generated/ignored folders whose module semantics lack `"type": "module"`. */
async function hasLooseJsFiles(dir: string, depth = 0): Promise<boolean> {
  if (depth > 3) return false;
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const entry of entries) {
    if (
      entry.name === "node_modules" ||
      entry.name === ".git" ||
      entry.name === DIST_DIR ||
      entry.name === ".fastagent" ||
      entry.name === ".state" ||
      entry.name === SECRETS_DIRNAME
    ) {
      continue;
    }
    if (entry.isSymbolicLink()) continue;
    if (entry.isFile() && entry.name.endsWith(".js")) return true;
    if (entry.isDirectory() && (await hasLooseJsFiles(join(dir, entry.name), depth + 1))) return true;
  }
  return false;
}

/** Static shape check for an existing `dist/`: accept FastAgent builds (even stale ones), refuse unrelated output. */
async function assertCompatibleDist(dir: string, shown: string): Promise<void> {
  const distPath = join(dir, DIST_DIR);
  const st = await lstatOrMissing(distPath);
  if (st === undefined) return;
  const conflict = () =>
    new Error(
      `"${shown}/${DIST_DIR}" does not look like a FastAgent build output — to keep existing build artifacts ` +
        `untouched, initialize the agent in a child directory (e.g. \`${CHILD_HINT}\`)`,
    );
  if (st.isSymbolicLink() || !st.isDirectory()) throw conflict();
  const buildPath = join(distPath, BUILD_FILE);
  const entryPath = join(distPath, "index.js");
  const [buildSt, entrySt] = await Promise.all([lstatOrMissing(buildPath), lstatOrMissing(entryPath)]);
  if (!buildSt?.isFile() || buildSt.isSymbolicLink() || !entrySt?.isFile() || entrySt.isSymbolicLink()) {
    throw conflict();
  }
  let record: unknown;
  try {
    record = JSON.parse(await readFile(buildPath, "utf8"));
  } catch {
    throw conflict();
  }
  if (
    !isPlainObject(record) ||
    !Array.isArray(record.code) ||
    !record.code.every((item) => typeof item === "string") ||
    typeof record.fingerprint !== "string"
  ) {
    throw conflict();
  }
  const entryText = await readFile(entryPath, "utf8");
  if (!entryText.includes(FASTAGENT_BUILD_MARKER) || !entryText.includes("defineDefinition(")) {
    throw conflict();
  }
}

interface ParsedSemver {
  prefix: "" | "^" | "~";
  major: number;
  minor: number;
  patch: number;
  prerelease: string | undefined;
}

function parseSemverSpec(spec: string): ParsedSemver | undefined {
  const match = SEMVER_SPEC.exec(spec.trim());
  if (!match) return undefined;
  return {
    prefix: (match[1] ?? "") as ParsedSemver["prefix"],
    major: Number(match[2]),
    minor: Number(match[3]),
    patch: Number(match[4]),
    prerelease: match[5],
  };
}

function compareSemver(a: ParsedSemver, b: ParsedSemver): number {
  if (a.major !== b.major) return a.major - b.major;
  if (a.minor !== b.minor) return a.minor - b.minor;
  return a.patch - b.patch;
}

function assertCompatibleDepSpec(pkgName: string, existing: unknown, required: string): void {
  if (typeof existing !== "string" || existing.trim() === "") {
    throw new Error(`package.json: dependency "${pkgName}" must be a non-empty version string`);
  }
  if (existing.trim() === required.trim()) return;
  const parsedExisting = parseSemverSpec(existing);
  const parsedRequired = parseSemverSpec(required);
  if (parsedExisting === undefined || parsedRequired === undefined) {
    throw new Error(
      `package.json: unrecognized version spec ${JSON.stringify(existing)} for "${pkgName}" ` +
        `(expected ${JSON.stringify(required)}); update it manually or use \`${CHILD_HINT}\``,
    );
  }
  if (parsedExisting.prerelease !== undefined || parsedRequired.prerelease !== undefined) {
    throw new Error(
      `package.json: incompatible prerelease version ${JSON.stringify(existing)} for "${pkgName}" ` +
        `(expected ${JSON.stringify(required)}); update it manually or use \`${CHILD_HINT}\``,
    );
  }
  const sameLine =
    parsedRequired.major === 0
      ? parsedExisting.major === 0 && parsedExisting.minor === parsedRequired.minor
      : parsedExisting.major === parsedRequired.major;
  if (!sameLine || compareSemver(parsedExisting, parsedRequired) < 0) {
    throw new Error(
      `package.json: incompatible version ${JSON.stringify(existing)} for "${pkgName}" ` +
        `(requires at least ${JSON.stringify(required)}); update it manually or use \`${CHILD_HINT}\``,
    );
  }
}

function isCompatibleScript(key: keyof typeof DEFAULT_SCRIPTS, value: unknown): boolean {
  if (typeof value !== "string") return false;
  return value === DEFAULT_SCRIPTS[key] || new RegExp(`\\bfastagent\\s+${key}\\b`).test(value);
}

/** Plan creation or conservative in-place merge for `package.json`. */
async function planPackageManifest(
  dir: string,
  shown: string,
  build: Awaited<ReturnType<typeof fastagentBuild>>,
): Promise<{ write?: PlannedWrite; dependenciesChanged: boolean; preserved: boolean }> {
  const rel = "package.json";
  const abs = join(dir, rel);
  const st = await lstatOrMissing(abs);
  if (st === undefined) {
    return {
      write: { rel, content: packageJson(toPackageName(dir), build), mode: "create" },
      dependenciesChanged: true,
      preserved: false,
    };
  }
  await assertSafeWriteTarget(dir, rel, "update");
  const raw = await readFile(abs, "utf8");
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new Error(`"${shown}/package.json" is not valid JSON: ${(error as Error).message}`);
  }
  if (!isPlainObject(parsed)) {
    throw new Error(`"${shown}/package.json" must contain a JSON object`);
  }

  const manifest: Record<string, unknown> = { ...parsed };
  let changed = false;
  let dependenciesChanged = false;

  if (manifest.type !== "module") {
    if (manifest.type !== undefined) {
      throw new Error(
        `"${shown}/package.json" sets "type": ${JSON.stringify(manifest.type)}, not "module" — refusing to change ` +
          `module semantics; initialize in a child directory instead (e.g. \`${CHILD_HINT}\`)`,
      );
    }
    if (await hasLooseJsFiles(dir)) {
      throw new Error(
        `"${shown}/package.json" omits "type": "module" while .js files exist in the directory — refusing to change ` +
          `their CommonJS semantics; set "type": "module" explicitly or initialize in a child directory (e.g. \`${CHILD_HINT}\`)`,
      );
    }
    manifest.type = "module";
    changed = true;
  }

  if (typeof manifest.name !== "string" || manifest.name.trim() === "") {
    manifest.name = toPackageName(dir);
    changed = true;
  }

  if (manifest.scripts !== undefined && !isPlainObject(manifest.scripts)) {
    throw new Error(`"${shown}/package.json": "scripts" must be an object`);
  }
  const scripts: Record<string, unknown> = isPlainObject(manifest.scripts) ? { ...manifest.scripts } : {};
  let scriptsChanged = manifest.scripts === undefined;
  for (const key of Object.keys(DEFAULT_SCRIPTS) as Array<keyof typeof DEFAULT_SCRIPTS>) {
    if (scripts[key] === undefined) {
      scripts[key] = DEFAULT_SCRIPTS[key];
      scriptsChanged = true;
    } else if (!isCompatibleScript(key, scripts[key])) {
      throw new Error(
        `"${shown}/package.json" already defines a conflicting "${key}" script (${JSON.stringify(scripts[key])}) — ` +
          `refusing to overwrite it; initialize in a child directory instead (e.g. \`${CHILD_HINT}\`)`,
      );
    }
  }
  if (scriptsChanged) {
    manifest.scripts = scripts;
    changed = true;
  }

  if (manifest.dependencies !== undefined && !isPlainObject(manifest.dependencies)) {
    throw new Error(`"${shown}/package.json": "dependencies" must be an object`);
  }
  if (manifest.devDependencies !== undefined && !isPlainObject(manifest.devDependencies)) {
    throw new Error(`"${shown}/package.json": "devDependencies" must be an object`);
  }
  const deps: Record<string, unknown> = isPlainObject(manifest.dependencies) ? { ...manifest.dependencies } : {};
  const devDeps: Record<string, unknown> = isPlainObject(manifest.devDependencies)
    ? { ...manifest.devDependencies }
    : {};
  const expected = expectedManifestDeps(build);

  let depsFieldChanged = false;
  for (const [name, required] of Object.entries(expected.dependencies)) {
    if (deps[name] === undefined) {
      deps[name] = required;
      depsFieldChanged = true;
      dependenciesChanged = true;
    } else {
      assertCompatibleDepSpec(name, deps[name], required);
    }
  }
  if (depsFieldChanged) {
    manifest.dependencies = deps;
    changed = true;
  }

  let devDepsFieldChanged = false;
  for (const [name, required] of Object.entries(expected.devDependencies)) {
    if (devDeps[name] !== undefined) {
      assertCompatibleDepSpec(name, devDeps[name], required);
    } else if (deps[name] !== undefined) {
      assertCompatibleDepSpec(name, deps[name], required);
    } else {
      devDeps[name] = required;
      devDepsFieldChanged = true;
      dependenciesChanged = true;
    }
  }
  if (devDepsFieldChanged) {
    manifest.devDependencies = devDeps;
    changed = true;
  }

  if (!changed) {
    return { dependenciesChanged: false, preserved: true };
  }
  return {
    write: { rel, content: `${JSON.stringify(manifest, null, 2)}\n`, mode: "update", previous: raw },
    dependenciesChanged,
    preserved: false,
  };
}

function appendLines(existing: string, lines: readonly string[]): string {
  const base = existing.length === 0 ? "" : existing.endsWith("\n") ? existing : `${existing}\n`;
  return `${base}${lines.join("\n")}\n`;
}

/** Plan creation or effective-protection update for root `.gitignore`. */
async function planRootGitignore(dir: string): Promise<{ write?: PlannedWrite; preserved: boolean }> {
  const rel = ".gitignore";
  const abs = join(dir, rel);
  const st = await lstatOrMissing(abs);
  if (st === undefined) {
    return { write: { rel, content: baseTemplate("gitignore"), mode: "create" }, preserved: false };
  }
  await assertSafeWriteTarget(dir, rel, "update");
  const raw = await readFile(abs, "utf8");
  const ig = ignore({ ignorecase: false }).add(raw);
  const missing = ROOT_IGNORE_RULES.filter(({ probe }) => !ig.ignores(probe)).map(({ rule }) => rule);
  if (missing.length === 0) return { preserved: true };
  const next = appendLines(raw, missing);
  const verified = ignore({ ignorecase: false }).add(next);
  for (const { probe, rule } of ROOT_IGNORE_RULES) {
    if (!verified.ignores(probe)) {
      throw new Error(`could not protect "${rule}" in .gitignore; check existing negation rules`);
    }
  }
  return { write: { rel, content: next, mode: "update", previous: raw }, preserved: false };
}

/** Plan creation or effective-protection update for `.secrets/.gitignore` (keep `.env.example` shareable). */
async function planSecretsGitignore(dir: string): Promise<{ write?: PlannedWrite; preserved: boolean }> {
  const rel = join(SECRETS_DIRNAME, ".gitignore");
  const abs = join(dir, rel);
  const st = await lstatOrMissing(abs);
  if (st === undefined) {
    return { write: { rel, content: baseTemplate("secrets.gitignore"), mode: "create" }, preserved: false };
  }
  await assertSafeWriteTarget(dir, rel, "update");
  const raw = await readFile(abs, "utf8");
  const ig = ignore({ ignorecase: false }).add(raw);
  const needIgnoreSecrets = !ig.ignores(".env") || !ig.ignores("auth.json");
  const needUnignoreGitignore = ig.ignores(".gitignore");
  const needUnignoreExample = ig.ignores(".env.example");
  if (!needIgnoreSecrets && !needUnignoreGitignore && !needUnignoreExample) {
    return { preserved: true };
  }
  const additions: string[] = [];
  if (needIgnoreSecrets) {
    additions.push("*", "!.gitignore", "!.env.example");
  } else {
    if (needUnignoreGitignore) additions.push("!.gitignore");
    if (needUnignoreExample) additions.push("!.env.example");
  }
  const next = appendLines(raw, additions);
  const verified = ignore({ ignorecase: false }).add(next);
  if (
    !verified.ignores(".env") ||
    !verified.ignores("auth.json") ||
    verified.ignores(".gitignore") ||
    verified.ignores(".env.example")
  ) {
    throw new Error(`could not protect ${SECRETS_DIRNAME}/.gitignore while keeping .env.example shareable`);
  }
  return { write: { rel, content: next, mode: "update", previous: raw }, preserved: false };
}

const git = gitFor("no repository was created");

/** Detect credentials already tracked in Git without touching the index. */
function detectTrackedSecrets(dir: string): string[] {
  let top: string | undefined;
  try {
    top = git.answer(["rev-parse", "--show-toplevel"], dir);
  } catch (error) {
    if (error instanceof GitNotInstalled) return [];
    throw error;
  }
  if (top === undefined) return [];
  let listed: string | undefined;
  try {
    listed = git.answer(["ls-files", "--", ".env", ".env.*", SECRETS_DIRNAME], dir);
  } catch (error) {
    if (error instanceof GitNotInstalled) return [];
    throw error;
  }
  if (!listed) return [];
  const shareable = new Set([`${SECRETS_DIRNAME}/.gitignore`, `${SECRETS_DIRNAME}/.env.example`]);
  return listed
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line !== "" && !shareable.has(line));
}

/**
 * Preflight and scaffold a runnable agent into `dir`:
 * - Fresh (missing, empty, or only Git metadata + placeholders): write the complete starter including example skill.
 * - Existing agent (has `fastagent.config.ts` or agent assets `SYSTEM.md`, `skills/`, `src/tools/`): preserve author
 *   files, fill only missing setup/compatible manifest fields/ignore protections, never restore the example skill.
 * - Conflicting/ambiguous host directory: fail before the first write.
 */
export async function scaffoldAgent(dir: string): Promise<ScaffoldResult> {
  const shown = displayPath(process.cwd(), dir) ?? dir;
  const owner = enclosingAgentDir(dir);
  if (owner) {
    throw new Error(
      `"${shown}" is inside the agent ${owner} — an agent is a directory of its own; create it outside that one`,
    );
  }
  const st = await lstatOrMissing(dir);
  if (st !== undefined && (st.isSymbolicLink() || !st.isDirectory())) {
    throw new Error(`"${shown}" exists and is not a directory`);
  }

  const rawEntries = st ? await readdir(dir) : [];
  const occupants = rawEntries.filter((name) => !IGNORABLE.includes(name) && name !== ".git");
  const isFresh = occupants.length === 0;
  const build = await fastagentBuild();

  const writes: PlannedWrite[] = [];
  const preserved: string[] = [];
  let dependenciesChanged = false;

  if (isFresh) {
    const skill = (name: string): PlannedWrite => ({
      rel: join("skills", "writing-great-skills", name),
      content: baseTemplate(`skills/writing-great-skills/${name}`),
      mode: "create",
    });
    writes.push(
      { rel: "SYSTEM.md", content: baseTemplate("SYSTEM.md"), mode: "create" },
      skill("SKILL.md"),
      skill("GLOSSARY.md"),
      skill("LICENSE"),
      { rel: AGENT_CONFIG_FILE, content: baseTemplate(AGENT_CONFIG_FILE), mode: "create" },
      { rel: ".gitignore", content: baseTemplate("gitignore"), mode: "create" },
      { rel: join(SECRETS_DIRNAME, ".gitignore"), content: baseTemplate("secrets.gitignore"), mode: "create" },
      { rel: join(SECRETS_DIRNAME, ".env.example"), content: baseTemplate("env.example"), mode: "create" },
      { rel: "package.json", content: packageJson(toPackageName(dir), build), mode: "create" },
    );
    dependenciesChanged = true;
  } else {
    if (!(await hasAgentAssets(dir))) {
      throw new Error(
        `"${shown}" is not empty (it holds ${occupants.join(", ")}) — to initialize an agent inside an existing ` +
          `project, run \`${CHILD_HINT}\``,
      );
    }
    await assertCompatibleDist(dir, shown);

    const optionalCreates: Array<{ rel: string; content: string }> = [
      { rel: "SYSTEM.md", content: baseTemplate("SYSTEM.md") },
      { rel: AGENT_CONFIG_FILE, content: baseTemplate(AGENT_CONFIG_FILE) },
      { rel: join(SECRETS_DIRNAME, ".env.example"), content: baseTemplate("env.example") },
    ];
    for (const item of optionalCreates) {
      const itemSt = await lstatOrMissing(join(dir, item.rel));
      if (itemSt === undefined) {
        writes.push({ rel: item.rel, content: item.content, mode: "create" });
      } else {
        if (!itemSt.isFile() && !itemSt.isSymbolicLink()) {
          throw new Error(`cannot initialize "${item.rel}": it exists and is not a file`);
        }
        preserved.push(item.rel);
      }
    }

    const pkgPlan = await planPackageManifest(dir, shown, build);
    dependenciesChanged = pkgPlan.dependenciesChanged;
    if (pkgPlan.write) writes.push(pkgPlan.write);
    else if (pkgPlan.preserved) preserved.push("package.json");

    const rootIgnorePlan = await planRootGitignore(dir);
    if (rootIgnorePlan.write) writes.push(rootIgnorePlan.write);
    else if (rootIgnorePlan.preserved) preserved.push(".gitignore");

    const secretsIgnorePlan = await planSecretsGitignore(dir);
    if (secretsIgnorePlan.write) writes.push(secretsIgnorePlan.write);
    else if (secretsIgnorePlan.preserved) preserved.push(join(SECRETS_DIRNAME, ".gitignore"));
  }

  for (const plan of writes) {
    await assertSafeWriteTarget(dir, plan.rel, plan.mode);
  }

  const createdDirs: string[] = [];
  const dirExisted = st !== undefined;
  if (!dirExisted) {
    await mkdir(dir, { recursive: true });
  }
  const applied: PlannedWrite[] = [];

  const undo = async (): Promise<void> => {
    for (const item of [...applied].reverse()) {
      const abs = join(dir, item.rel);
      if (item.mode === "create") {
        await rm(abs, { force: true }).catch(() => {});
      } else if (item.previous !== undefined) {
        try {
          writeFileAtomic(abs, item.previous);
        } catch {
          // Best-effort rollback while reporting the primary I/O failure.
        }
      }
    }
    for (const rel of [...createdDirs].sort((a, b) => b.split(sep).length - a.split(sep).length)) {
      await rmdir(join(dir, rel)).catch(() => {});
    }
    if (!dirExisted) await rmdir(dir).catch(() => {});
  };

  try {
    for (const plan of writes) {
      const abs = join(dir, plan.rel);
      const parentRel = dirname(plan.rel);
      if (parentRel !== "." && parentRel !== "") {
        const missingDirs: string[] = [];
        for (let p = parentRel; p !== "." && p !== ""; p = dirname(p)) {
          if ((await lstatOrMissing(join(dir, p))) === undefined) missingDirs.push(p);
          else break;
        }
        if (missingDirs.length > 0) {
          await mkdir(join(dir, parentRel), { recursive: true });
          for (const p of missingDirs) {
            if (!createdDirs.includes(p)) createdDirs.push(p);
          }
        }
      }
      if (plan.mode === "create") {
        await writeFile(abs, plan.content, { flag: "wx" });
      } else {
        writeFileAtomic(abs, plan.content);
      }
      applied.push(plan);
    }
  } catch (error) {
    await undo();
    throw error;
  }

  const trackedSecrets = st !== undefined ? detectTrackedSecrets(dir) : [];

  return {
    dir,
    mode: isFresh ? "fresh" : "existing",
    created: applied.filter((w) => w.mode === "create").map((w) => w.rel),
    updated: applied.filter((w) => w.mode === "update").map((w) => w.rel),
    preserved,
    dependenciesChanged,
    trackedSecrets,
    undo,
  };
}

/**
 * Make a genuinely new standalone agent a git repository whose first commit is what `init` wrote.
 * Never stages, alters the index, or creates extra commits during adoption, rerun, or inside an existing repository.
 */
export async function initRepository(dir: string, options: { mode?: "fresh" | "existing" } = {}): Promise<string> {
  const mode = options.mode ?? "fresh";
  const reason = (error: unknown) => (error as Error).message.split("\n")[0];
  try {
    const enclosing = git.answer(["rev-parse", "--show-toplevel"], dir);
    if (enclosing !== undefined && git.answer(["check-ignore", "-q", "."], dir) === undefined) {
      return `inside the git repository ${enclosing}: it tracks the agent, so none was created`;
    }
    if (mode === "existing") {
      return "existing directory: skipped git initialization";
    }
    await git.run(["init", "--quiet"], dir);
    await git.run(["add", "--all"], dir);
  } catch (error) {
    if (error instanceof GitNotInstalled) return error.message;
    return `git could not create a repository: ${reason(error)}`;
  }
  try {
    await git.run(["commit", "--quiet", "--message", "Create the agent with fastagent"], dir);
  } catch (error) {
    return `created a git repository, but its first commit failed (${reason(error)}): commit the scaffold yourself`;
  }
  return "created a git repository, with the scaffold as its first commit";
}
