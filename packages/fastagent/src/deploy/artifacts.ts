/**
 * What a command that writes the container may write, under ONE ownership rule: a file fastagent did not generate is
 * the author's and is never touched; one it generated is kept unless `force` regenerates it.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { exists } from "../paths.ts";
import { type Artifact, type ContainerTarget, isGeneratedDockerfile, isGeneratedDockerignore } from "./container.ts";

/** One artifact's verdict under the ownership rule: the bytes to write, or `undefined` to keep what is there. */
export interface ArtifactStep {
  readonly abs: string;
  readonly content: string | undefined;
  readonly message: string;
}

/** Pure ownership verdict for one artifact given its on-disk content (if any). */
function decideArtifactStep(
  artifact: Readonly<Artifact>,
  abs: string,
  existing: string | undefined,
  force: boolean,
  container: Pick<ContainerTarget, "writtenBy" | "command">,
): ArtifactStep {
  const { path, content } = artifact;
  if (existing !== undefined && !isOurs(path, existing)) {
    return {
      abs,
      content: undefined,
      message:
        `[fastagent] kept ${path} — not generated by fastagent, so --force does not touch it ` +
        `(delete it to let ${container.writtenBy} own the path)` +
        (path === ".dockerignore"
          ? "; see the warnings above for what it must exclude"
          : `; the container must still run \`${container.command.join(" ")}\``),
    };
  }
  if (existing !== undefined && !force) {
    return {
      abs,
      content: undefined,
      message:
        existing === content
          ? `[fastagent] kept ${path} (unchanged)`
          : `[fastagent] kept ${path} — it no longer matches what ${container.writtenBy} would generate; pass --force to regenerate.`,
    };
  }
  return { abs, content, message: `[fastagent] wrote ${path}` };
}

/** What each artifact under `target` becomes, under the ownership rule. */
export async function planArtifacts(
  dir: string,
  artifacts: readonly Artifact[],
  force: boolean,
  container: Pick<ContainerTarget, "writtenBy" | "command">,
): Promise<ArtifactStep[]> {
  return Promise.all(
    artifacts.map(async (artifact) => {
      const abs = join(dir, artifact.path);
      const existing = (await exists(abs)) ? await readFile(abs, "utf8") : undefined;
      return decideArtifactStep(artifact, abs, existing, force, container);
    }),
  );
}

/** Carry out a {@link planArtifacts} decision. Reports each path, written or kept. */
export async function applyArtifactPlan(steps: readonly ArtifactStep[]): Promise<void> {
  for (const step of steps) {
    if (step.content !== undefined) {
      await mkdir(dirname(step.abs), { recursive: true });
      await writeFile(step.abs, step.content);
    }
    console.error(step.message);
  }
}

/** The container's two files, each known by its first line. */
function isOurs(path: string, content: string): boolean {
  return path === ".dockerignore" ? isGeneratedDockerignore(content) : isGeneratedDockerfile(content);
}
