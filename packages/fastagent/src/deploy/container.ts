/** The portable container — Dockerfile + .dockerignore, host-neutral: what a platform adds is its {@link ContainerTarget}. */
import { DEPLOYED_ENV, INSTANCES_DIRNAME, SECRETS_DIRNAME, STATE_DIRNAME } from "../paths.ts";
import { INSTANCE_NAME_ENV } from "../instance-name.ts";
import { NODE_FLOOR } from "../runtime.ts";

export interface Artifact {
  path: string;
  content: string;
}

/** Where a generated image keeps its storage (`FASTAGENT_ROOT`): the container mounts its volume here. */
export const STORAGE_DIR = "/data";

/** Where a generated image holds the agent: the build context, which is the agent directory. */
const IMAGE_APP_DIR = "/app";

/** The first line of every file fastagent generates for a container, whichever command wrote it. */
const GENERATED_MARKER = "# Generated by `fastagent ";

const markerOf = (writtenBy: string): string => `${GENERATED_MARKER}${writtenBy.replace(/^fastagent /, "")}\``;

/** The ONE predicate for "did fastagent generate this Dockerfile?". */
export function isGeneratedDockerfile(content: string): boolean {
  return content.startsWith(GENERATED_MARKER);
}

export function isGeneratedDockerignore(content: string): boolean {
  return content.startsWith(GENERATED_MARKER);
}

/** What a platform makes of the portable container. */
export interface ContainerTarget {
  /** The command that writes the files, named in their first line: `fastagent deploy init docker`. */
  writtenBy: string;
  /** What the image runs, in the agent directory at {@link IMAGE_APP_DIR}. */
  command: readonly string[];
  /**
   * Where the instance keeps its state: a volume at {@link STORAGE_DIR} the container takes as a deployed box (one
   * container, one instance), or a database the platform gives it, so the container holds nothing that must survive.
   */
  storage: "volume" | "database";
  /** The HTTP port the image listens on (`EXPOSE <port>`), so container platforms detect it without guessing. */
  port?: number;
  /** What else the image leaves out: the platform's own project files. */
  ignore?: readonly string[];
}

/** Standard container target: `fastagent start` on a volume, listening on port 8787. */
export const DOCKER_TARGET: ContainerTarget = {
  writtenBy: "fastagent deploy init docker",
  command: ["./node_modules/.bin/fastagent", "start"],
  storage: "volume",
  port: 8787,
};

export interface ContainerInput {
  target: ContainerTarget;
  /** The agent the image runs, set as `FASTAGENT_NAME` on a volume: the agent its storage belongs to. */
  name: string;
  /** Whether `package-lock.json` exists: the image installs from it with `npm ci`. */
  hasLockfile: boolean;
  /** Debian packages the image installs (`git` for a shipped `.git`). */
  apt?: string[];
  /** Agent-dir-relative machinery paths the NAME-based excludes below would miss. */
  machineryPaths?: string[];
}

/** The apt layer (cached right after FROM). */
function aptLayer(packages?: string[]): string {
  return packages && packages.length > 0
    ? `RUN apt-get update \\
 && apt-get install -y --no-install-recommends ${packages.join(" ")} \\
 && rm -rf /var/lib/apt/lists/*
`
    : "";
}

/**
 * The Node image an agent runs on: the newest of the floor's line. A floating tag, so every build pulls it
 * (`docker build --pull`): a copy cached before the floor's release would start a Node the CLI refuses.
 */
const NODE_IMAGE = `node:${NODE_FLOOR.split(".")[0]}-slim`;

/** Why the image builds `dist/` itself: a build context that follows `.gitignore` drops it, and `start` needs it. */
const BUILD_STEP_NOTE =
  "# `start` opens dist/, which a build context that follows .gitignore leaves out: build it here.";

function dockerfile(input: ContainerInput): string {
  // The build context is the agent directory, baked at IMAGE_APP_DIR; deps install (and the local bin lives)
  // there.
  const dir = IMAGE_APP_DIR;
  const layoutNote = `The agent directory is baked at ${dir}`;
  // apt layer right after FROM (cached across code changes): the agent's tools may shell out to git etc., which the
  // slim image lacks.
  const apt = aptLayer(input.apt);
  const { target } = input;
  // The caches stay off the volume: they are rebuildable, and a host mount is the slow disk.
  const volume =
    target.storage === "volume"
      ? `ENV ${DEPLOYED_ENV}=1\nENV ${INSTANCE_NAME_ENV}=${input.name}\nENV FASTAGENT_ROOT=${STORAGE_DIR}\n`
      : "";
  const deployment = `${volume}ENV npm_config_cache=/tmp/fastagent/npm\n`;
  const note = "# npm-based — for pnpm/yarn, adapt the install line + the lockfile COPY (corepack enable, etc.).";
  const head = `${markerOf(target.writtenBy)}. ${layoutNote}
${note}
FROM ${NODE_IMAGE}
${apt}WORKDIR ${dir}
${deployment}`;
  // Install ALL deps (no --omit=dev / --production): an agent's tools may need its full toolchain.
  //
  // `*.tgz` RIDES ALONG with the manifest, because the install layer runs BEFORE `COPY . .` and a
  // `"dep": "file:./something.tgz"` resolves against the directory it is installing in. Without this the file is
  // not there yet and the build fails on a dependency the author can see sitting in the agent directory.
  // `npm ci` requires a lockfile and hard-fails without one (a common `init --no-install` agent); fall back to `npm
  // install` when there is none so the build never breaks.
  const install = input.hasLockfile ? "npm ci" : "npm install";
  const expose = target.port === undefined ? "" : `EXPOSE ${target.port}\n`;
  return `${head}COPY package.json package-lock.json* *.tgz ./
RUN ${install}
COPY . .
${BUILD_STEP_NOTE}
RUN ./node_modules/.bin/fastagent build
${expose}CMD [${target.command.map((part) => JSON.stringify(part)).join(", ")}]
`;
}

/** Patterns are RECURSIVE (`**​/`) on purpose. */
const dockerignore = (input: ContainerInput): string =>
  `${markerOf(input.target.writtenBy)}. Delete this line to take ownership (${input.target.writtenBy} then keeps your file).\n` +
  DOCKERIGNORE_BASE +
  (input.target.ignore ?? []).map((p) => `/${p}\n`).join("") +
  (input.machineryPaths ?? [])
    // Skip what the name-based rules above already cover: the default `.secrets` / `.state` and anything inside them.
    .filter((p) => [SECRETS_DIRNAME, STATE_DIRNAME].every((covered) => p !== covered && !p.startsWith(`${covered}/`)))
    .map((p) => `# resolved machinery path\n/${p}\n`)
    .join("");

const DOCKERIGNORE_BASE = `**/node_modules
**/${SECRETS_DIRNAME}/**
**/${STATE_DIRNAME}
/${INSTANCES_DIRNAME}
**/.cache
**/.env
**/.env.*
**/*.env
!**/.env.example
!**/${SECRETS_DIRNAME}/.gitignore
**/*.log
# .git is deliberately shipped with the definition (the generated image installs git when the directory ships
# a .git). For a smaller image with no git needs, add a ".git" line here.
`;

/** The Dockerfile and its ignore file. */
export function containerArtifacts(input: ContainerInput): Artifact[] {
  return [
    { path: "Dockerfile", content: dockerfile(input) },
    { path: ".dockerignore", content: dockerignore(input) },
  ];
}
