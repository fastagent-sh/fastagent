describe("cli: deploy", () => {
  it("keeps the file --env-file names out of the image when it is in the agent directory: excluded by its path, and a kept ignore file that lacks it stops --run", async () => {
    const dir = await agentWorkspace("fa-deploy-valuefile-", {
      "fastagent.config.ts": `export default { defaults: { model: "openai/gpt-4o-mini" } };\n`,
    });
    // `prod.env` is neither `.env` nor `.env.*`: no name rule of the generated files reaches it.
    const file = join(dir, "prod.env");
    await writeFile(file, "OPENAI_API_KEY=sk-in-the-directory\n");
    for (const host of ["docker", "railway"]) {
      const result = await runInProcess(["deploy", host, dir, "--env-file", file]);
      expect(result.code, result.stderr).toBe(0);
    }
    const ships = (rules: string, path: string) => !ignore().add(rules).ignores(path);
    expect(ships(await readFile(join(dir, ".dockerignore"), "utf8"), "prod.env")).toBe(false);
    expect(ships(await readFile(join(dir, ".railwayignore"), "utf8"), "prod.env")).toBe(false);
    // Without it, nothing is added: the files are the ones every deploy writes.
    const plain = await agentWorkspace("fa-deploy-valuefile-none-", {
      "fastagent.config.ts": `export default { defaults: { model: "openai/gpt-4o-mini" } };\n`,
    });
    await runInProcess(["deploy", "docker", plain]);
    expect(await readFile(join(plain, ".dockerignore"), "utf8")).not.toContain("prod.env");

    // The author's own ignore file is theirs: it is refused under --run when it would upload the secrets, and the
    // line to add is named; it is only a warning when generating.
    await writeFile(
      join(dir, ".dockerignore"),
      "**/node_modules\n**/.secrets/**\n**/.state\n**/.env\n/.fastagent\n!/.fastagent/deploy\n/content\n",
    );
    const gated = await runInProcess(["deploy", "docker", dir, "--env-file", file, "--run"]);
    expect(gated.code).toBe(1);
    expect(gated.stderr).toMatch(/does not exclude `prod\.env` — the build context would BAKE SECRETS INTO THE IMAGE/);
    expect(gated.stderr).toContain("`/prod.env`");
    const planned = await runInProcess(["deploy", "docker", dir, "--env-file", file]);
    expect(planned.stderr).toMatch(/warn: your \.dockerignore \(kept\) does not exclude `prod\.env`/);
  });

  it("deploy WIRES the ownership rule — the real command keeps a file it did not generate", async () => {
    // The rule itself (exists x ours x force) is a state machine, tested at its own level in
    // test/deploy-artifacts.test.ts; eight spawns proving it here made this the slowest and only flaky
    // test in the suite. What a subprocess is for is the WIRING: that the command actually consults it.
    const dir = await agentWorkspace("fa-deploy-ignore-", {
      "fastagent.config.ts": `export default { defaults: { model: "${CODEX_MODEL}" } };\n`,
      "package.json": `{"type":"module"}`,
    });
    expect((await runInProcess(["deploy", "fly", dir])).code).toBe(0);
    expect(await readFile(join(dir, ".dockerignore"), "utf8")).toMatch(/^# Generated by/);
    // Artifacts land in the agent directory.
    expect(await readFile(join(dir, "Dockerfile"), "utf8")).toMatch(/agent directory is baked at \/app$/m);
    expect(await readFile(join(dir, flyTomlFile(await deploymentName(dir))), "utf8")).toMatch(/FASTAGENT_SECRETS_DIR/);

    const hostIgnore = "# the author's own rules\n.git\ndist\n"; // no marker → the author's
    await writeFile(join(dir, ".dockerignore"), hostIgnore);
    const forced = await runInProcess(["deploy", "fly", dir, "--force"]);
    expect(forced.code).toBe(0);
    // The safety boundary docs/deploy.md promises: --force NEVER clobbers the author's file.
    expect(await readFile(join(dir, ".dockerignore"), "utf8")).toBe(hostIgnore);
    expect(forced.stderr).toMatch(/kept \.dockerignore — not generated by fastagent/);
    expect(forced.stderr).toMatch(/BAKE SECRETS INTO THE IMAGE/); // the critical kept-file warn fired (not force-gated)
    expect(forced.stderr).toMatch(/excludes \.git/); // …and the history note
  });
});

describe("cli: destroy agentcore", () => {
  const withForeignBucket = () =>
    recordHostCli("aws", ({ args }) => {
      if (args[0] === "sts") return { stdout: JSON.stringify({ Account: "123456789012" }) };
      if (args[0] === "scheduler") return { stdout: JSON.stringify({ Schedules: [] }) };
      if (args[0] === "s3api" && args[1] === "list-object-versions") {
        return { stdout: JSON.stringify({ Versions: [{ Key: "state/snapshot.json.gz", VersionId: "v1" }] }) };
      }
      if (args[0] === "logs" && args[1] === "describe-log-groups") return { stdout: "[]" };
      return { stdout: "{}" };
    });

  it("refuses an unsupported host with exit 2 and gates when aws is missing", async () => {
    const dir = await agentWorkspace("fa-destroy-refuse-");
    const unsupported = await runInProcess(["destroy", "fly", dir]);
    expect(unsupported.code).toBe(2);
    expect(unsupported.stderr).toMatch(/Allowed choices are agentcore/);

    const missingAws = await runInProcess(["destroy", "agentcore", dir], undefined, {
      ...process.env,
      AWS_REGION: "us-west-2",
    });
    expect(missingAws.code).toBe(1);
    expect(missingAws.stderr).toContain("destroy stopped: aws CLI not found");
  });

  it("dry-run reports resources without deleting; --run deletes deployment resources while keeping foreign bucket data", async () => {
    const dir = await agentWorkspace("fa-destroy-run-", {
      "fastagent.config.ts": `export default { name: "my-agent", defaults: { model: "openai/gpt-4o-mini" } };\n`,
    });
    const env = { ...process.env, AWS_REGION: "us-west-2" };

    const dryAws = withForeignBucket();
    const dryRun = await runInProcess(["destroy", "agentcore", dir], undefined, env);
    expect(dryRun.code, dryRun.stderr).toBe(0);
    expect(dryRun.stdout).toContain("what a deploy of");
    expect(dryRun.stdout).toContain("NOT MINE TO DELETE: bucket");
    expect(dryRun.stdout).toContain("nothing was deleted. Re-run with --run to delete all of it.");
    expect(dryAws.cmds().some((cmd) => cmd.includes("delete-"))).toBe(false);

    const runAws = withForeignBucket();
    const deleted = await runInProcess(["destroy", "agentcore", dir, "--run"], undefined, env);
    expect(deleted.code, deleted.stderr).toBe(0);
    expect(deleted.stdout).toContain("deleted:");
    expect(deleted.stdout).toContain("KEPT: bucket");
    expect(runAws.cmds()).toEqual(
      expect.arrayContaining([
        expect.stringContaining("cloudformation delete-stack"),
        expect.stringContaining("ecr delete-repository"),
        expect.stringContaining("secretsmanager delete-secret"),
      ]),
    );
    expect(runAws.cmds().some((cmd) => cmd.startsWith("s3api delete-"))).toBe(false);
  });
});

describe("cli: logs agentcore", () => {
  it("refuses an unsupported host or invalid --source with exit 2, and refuses when the stack is absent", async () => {
    const dir = await agentWorkspace("fa-logs-refuse-");
    expect((await runInProcess(["logs", "fly", dir])).code).toBe(2);

    const badSource = await runInProcess(["logs", "agentcore", dir, "--source", "other"]);
    expect(badSource.code).toBe(2);
    expect(badSource.stderr).toContain('logs: --source must be "runtime" or "forwarder"');

    recordHostCli("aws", ({ args }) =>
      args[0] === "cloudformation" ? { code: 254, stderr: "Stack with id fastagent-bot does not exist" } : {},
    );
    const absent = await runInProcess(["logs", "agentcore", dir, "--source", "forwarder"]);
    expect(absent.code).toBe(1);
    expect(absent.stderr).toMatch(/no AgentCore stack .* deploy it first/);
  });

  it("discovers the runtime log group from stack outputs and tails it with --since", async () => {
    const dir = await agentWorkspace("fa-logs-ok-", {
      "fastagent.config.ts": `export default { name: "my-agent", defaults: { model: "openai/gpt-4o-mini" } };\n`,
    });
    const aws = recordHostCli("aws", ({ args }) => {
      if (args[0] === "cloudformation") {
        return {
          stdout: JSON.stringify([
            {
              OutputKey: "RuntimeArn",
              OutputValue: "arn:aws:bedrock-agentcore:us-west-2:123456789012:runtime/rt_123",
            },
          ]),
        };
      }
      if (args[0] === "logs" && args[1] === "describe-log-groups") {
        return { stdout: JSON.stringify(["/aws/bedrock-agentcore/runtimes/rt_123-DEFAULT"]) };
      }
      return {};
    });

    const tailed = await runInProcess(["logs", "agentcore", dir, "--since", "10m"]);
    expect(tailed.code, tailed.stderr).toBe(0);
    expect(tailed.stderr).toContain("runtime → /aws/bedrock-agentcore/runtimes/rt_123-DEFAULT");
    expect(aws.cmds()).toContain("logs tail /aws/bedrock-agentcore/runtimes/rt_123-DEFAULT --format short --since 10m");
  });
});
