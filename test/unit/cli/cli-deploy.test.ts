import { describe, expect, it, vi } from "vitest";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { agentWorkspace, runInProcess } from "../../doubles/cli-run.ts";
import { CODEX_MODEL } from "../../doubles/codex-model.ts";

vi.mock("../../../packages/fastagent/src/git.ts", () => import("../../doubles/git-double.ts"));

describe("cli: deploy init", () => {
  it("writes docker container files (with EXPOSE 8787), prints commands, and never replaces author-owned files", async () => {
    const dir = await agentWorkspace("fa-deploy-", {
      "fastagent.config.ts": `export default { model: "${CODEX_MODEL}" };\n`,
      "package.json": JSON.stringify({ type: "module", name: "reviewer" }),
    });
    const first = await runInProcess(["-C", dir, "deploy", "init", "docker"]);
    expect(first.code, first.stderr).toBe(0);
    expect(first.stdout).toMatch(/^docker build --pull -t reviewer \.$/m);
    expect(first.stdout).toMatch(/^docker run .* -v reviewer-data:\/data .*-p 8787:8787 reviewer$/m);
    const dockerfile = await readFile(join(dir, "Dockerfile"), "utf8");
    expect(dockerfile).toMatch(/^ENV FASTAGENT_NAME=reviewer$/m);
    expect(dockerfile).toMatch(/^EXPOSE 8787$/m);
    expect(await readFile(join(dir, ".dockerignore"), "utf8")).toMatch(/^# Generated by/);

    const mine = "# the author's own rules\n.git\ndist\n";
    await writeFile(join(dir, ".dockerignore"), mine);
    const forced = await runInProcess(["-C", dir, "deploy", "init", "docker", "--force"]);
    expect(forced.code, forced.stderr).toBe(0);
    expect(await readFile(join(dir, ".dockerignore"), "utf8")).toBe(mine);
    expect(forced.stderr).toMatch(/kept \.dockerignore — not generated by fastagent/);
    expect(forced.stderr).toMatch(/does not exclude `\.secrets\/auth\.json` — the build context would BAKE SECRETS/);
  });

  it("writes compose.yml and fly.toml once (keeping user edits under --force), and railway without deprecated railway.json", async () => {
    const composeDir = await agentWorkspace("fa-deploy-compose-", {
      "package.json": JSON.stringify({ type: "module", name: "_Support" }),
    });
    const composed = await runInProcess(["-C", composeDir, "deploy", "init", "compose"]);
    expect(composed.code, composed.stderr).toBe(0);
    expect(composed.stdout).toContain("docker compose up -d --build");
    const composeYml = await readFile(join(composeDir, "compose.yml"), "utf8");
    expect(composeYml).toContain("agent_data:/data");
    expect(composeYml).toContain("http://127.0.0.1:8787/health");
    expect(await readFile(join(composeDir, ".dockerignore"), "utf8")).toMatch(/^\/compose\.yml$/m);
    await writeFile(join(composeDir, "compose.yml"), "# custom compose\n");
    const composeAgain = await runInProcess(["-C", composeDir, "deploy", "init", "compose", "--force"]);
    expect(composeAgain.code, composeAgain.stderr).toBe(0);
    expect(await readFile(join(composeDir, "compose.yml"), "utf8")).toBe("# custom compose\n");

    const flyDir = await agentWorkspace("fa-deploy-fly-", {
      "package.json": JSON.stringify({ type: "module", name: "_Support_Bot" }),
    });
    const flown = await runInProcess(["-C", flyDir, "deploy", "init", "fly"]);
    expect(flown.code, flown.stderr).toBe(0);
    expect(flown.stdout).toContain("fly launch --copy-config --ha=false --no-deploy");
    expect(flown.stdout).toContain("fly deploy --ha=false");
    const flyToml = await readFile(join(flyDir, "fly.toml"), "utf8");
    expect(flyToml).toContain('app = "support-bot"');
    expect(flyToml).toContain('destination = "/data"');
    expect(flyToml).toContain('auto_stop_machines = "off"');
    expect(flyToml).toContain("min_machines_running = 1");
    expect(flyToml).toContain('path = "/health"');
    expect(await readFile(join(flyDir, ".dockerignore"), "utf8")).toMatch(/^\/fly\.toml$/m);
    await writeFile(join(flyDir, "fly.toml"), "# custom fly\n");
    await runInProcess(["-C", flyDir, "deploy", "init", "fly", "--force"]);
    expect(await readFile(join(flyDir, "fly.toml"), "utf8")).toBe("# custom fly\n");

    const railwayDir = await agentWorkspace("fa-deploy-railway-", {
      "package.json": JSON.stringify({ type: "module", name: "ops" }),
    });
    const railed = await runInProcess(["-C", railwayDir, "deploy", "init", "railway"]);
    expect(railed.code, railed.stderr).toBe(0);
    expect(railed.stdout).toContain("railway volume add --mount-path /data");
    expect(railed.stdout).toContain("railway up");
    expect(existsSync(join(railwayDir, "railway.json"))).toBe(false);
    expect(existsSync(join(railwayDir, "railway.toml"))).toBe(false);
  });

  it("prints an image name Docker accepts when the agent's name has an uppercase letter or a leading separator", async () => {
    const dir = await agentWorkspace("fa-deploy-image-", {
      "package.json": JSON.stringify({ type: "module", name: "_Support" }),
    });
    const written = await runInProcess(["-C", dir, "deploy", "init", "docker"]);
    expect(written.code, written.stderr).toBe(0);
    expect(written.stdout).toMatch(/^docker build --pull -t support \.$/m);
    expect(written.stdout).toMatch(/^docker run -d --name _Support .* -v _Support-data:\/data .* support$/m);
  });

  it("delegates extension targets when installed and exits 2 naming the package (never auto-installing) when missing", async () => {
    const dir = await agentWorkspace("fa-deploy-ext-");
    const missing = await runInProcess(["-C", dir, "deploy", "init", "cloudflare"]);
    expect([missing.code, missing.stdout]).toEqual([2, ""]);
    expect(missing.stderr).toContain("@fastagent-sh/cloudflare");
    expect(missing.stderr).toContain("fastagent deploy init cloudflare");

    const invalid = await runInProcess(["-C", dir, "deploy", "init", "../evil"]);
    expect([invalid.code, invalid.stdout]).toEqual([2, ""]);
    expect(invalid.stderr).toContain('unknown deploy target "../evil"');

    const extDir = join(dir, "node_modules", "@fastagent-sh", "demo");
    await mkdir(extDir, { recursive: true });
    await writeFile(
      join(extDir, "package.json"),
      JSON.stringify({ name: "@fastagent-sh/demo", type: "module", exports: { "./cli": "./cli.js" } }),
    );
    await writeFile(join(extDir, "cli.js"), "export async function run(args) { console.log(JSON.stringify(args)); }\n");
    const delegated = await runInProcess(["-C", dir, "deploy", "init", "demo", "--force", "--no-install"]);
    expect([delegated.code, JSON.parse(delegated.stdout)], delegated.stderr).toEqual([
      0,
      ["init", "--force", "--no-install"],
    ]);
  });

  it("a container the image marks as deployed refuses to start without the agent its storage belongs to", async () => {
    const dir = await agentWorkspace("fa-deploy-owner-");
    const root = await mkdtemp(join(tmpdir(), "fa-deploy-root-"));
    const started = await runInProcess(["-C", dir, "start"], undefined, {
      ...process.env,
      FASTAGENT_DEPLOYED: "1",
      FASTAGENT_ROOT: root,
      FASTAGENT_NAME: "",
    });
    expect(started.code).toBe(1);
    expect(started.stderr).toContain("FASTAGENT_NAME is required for a deployment");
  });
});

describe("cli: deploy check", () => {
  it("exits 0 after deploy init, and exits 1 with JSON or stderr details on missing/leaking .dockerignore or broken definition", async () => {
    const dir = await agentWorkspace("fa-deploy-check-", {
      "fastagent.config.ts": `export default { model: "${CODEX_MODEL}" };\n`,
    });
    // Before `.dockerignore` exists, `.secrets/auth.json` would upload: exit 1.
    const unignored = await runInProcess(["-C", dir, "deploy", "check", "--json"]);
    expect(unignored.code).toBe(1);
    expect(JSON.parse(unignored.stdout)).toMatchObject({
      ok: false,
      leaks: [expect.stringContaining("there is no .dockerignore")],
    });

    // After `deploy init docker`, the generated `.dockerignore` excludes `.secrets/`: exit 0.
    expect((await runInProcess(["-C", dir, "deploy", "init", "docker"])).code).toBe(0);
    const clean = await runInProcess(["-C", dir, "deploy", "check"]);
    expect([clean.code, clean.stdout.trim()], clean.stderr).toEqual([0, "ok"]);
    const cleanJson = await runInProcess(["-C", dir, "deploy", "check", "--json"]);
    expect([cleanJson.code, JSON.parse(cleanJson.stdout).ok]).toEqual([0, true]);

    // A kept `.dockerignore` that drops `.secrets/` fails exit 1.
    await writeFile(join(dir, ".dockerignore"), "node_modules\n");
    const leaking = await runInProcess(["-C", dir, "deploy", "check"]);
    expect([leaking.code, leaking.stdout]).toEqual([1, ""]);
    expect(leaking.stderr).toContain("BAKE SECRETS INTO THE IMAGE");

    // A broken definition fails the gate (exit 1).
    await rm(join(dir, ".dockerignore"));
    await mkdir(join(dir, "src", "tools"), { recursive: true });
    await writeFile(join(dir, "src", "tools", "bad.ts"), "throw new Error('broken tool');\n");
    const broken = await runInProcess(["-C", dir, "deploy", "check", "--json"]);
    expect(broken.code).toBe(1);
    expect(JSON.parse(broken.stdout)).toMatchObject({
      ok: false,
      gate: expect.stringContaining("broken tool"),
    });
  });
});
