import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import ignore from "ignore";
import { describe, expect, it, vi } from "vitest";
import { applyArtifactPlan, planArtifacts } from "../../../packages/fastagent/src/deploy/artifacts.ts";
import { DOCKER_TARGET, containerArtifacts } from "../../../packages/fastagent/src/deploy/container.ts";

const input = { target: DOCKER_TARGET, name: "reviewer", hasLockfile: true };

describe("deploy/container: the portable image", () => {
  it("keeps tracked secrets scaffolds without shipping credentials, value files or state", () => {
    const artifacts = containerArtifacts(input);
    const rootIgnore = artifacts.find((artifact) => artifact.path === ".dockerignore")!.content;

    // One ignore file serves both builders: a second one beside the Dockerfile would shadow an author's own.
    expect(artifacts.map((artifact) => artifact.path)).not.toContain("Dockerfile.dockerignore");
    expect(rootIgnore).not.toMatch(/^\*\*\/\.secrets$/m);

    // Excluding descendants rather than the directory keeps these negations meaningful in both
    // Docker's matcher and the stricter gitignore-style matcher the pre-flight uses.
    const ignored = ignore({ ignorecase: false }).add(rootIgnore);
    const ships = (path: string): boolean => !ignored.ignores(path);
    const tracked = ["README.md", ".secrets/.env.example", ".secrets/.gitignore"];
    const sensitive = [
      ".secrets/.env",
      ".secrets/auth.json",
      ".secrets/nested/token",
      ".env",
      ".env.production",
      // A value file a person named, which no `.env` rule reaches.
      "prod.env",
      ".state/sessions/session.jsonl",
      ".state/sessions/demo.json",
      ".fastagent/dev/.state/agent.sqlite",
      ".fastagent/start/.state/agent.sqlite",
    ];

    expect(tracked.filter((path) => !ships(path))).toEqual([]);
    expect(sensitive.filter(ships)).toEqual([]);
    expect(ships(".git/HEAD")).toBe(true);
  });

  it("marks the container as a deployed box that names its agent, and carries no instance value", () => {
    const dockerfile = containerArtifacts(input).find((artifact) => artifact.path === "Dockerfile")!.content;
    expect(dockerfile).toMatch(/^ENV FASTAGENT_DEPLOYED=1$/m);
    expect(dockerfile).toMatch(/^ENV FASTAGENT_NAME=reviewer$/m);
    expect(dockerfile).toMatch(/^ENV FASTAGENT_ROOT=\/data$/m);
    expect(dockerfile).toMatch(/^EXPOSE 8787$/m);
    for (const name of ["FASTAGENT_MODEL", "FASTAGENT_API_KEY"]) expect(dockerfile).not.toContain(name);
  });
});

describe("deploy init: ownership decides what --force may replace", () => {
  const MARKER = "# Generated by `fastagent deploy init docker`";
  const PATHS = ["Dockerfile", ".dockerignore"] as const;
  const generated = `${MARKER}\nfresh\n`;

  async function attempt(
    path: (typeof PATHS)[number],
    existing: string | undefined,
    force: boolean,
  ): Promise<{ content: string; said: string }> {
    const dir = await mkdtemp(join(tmpdir(), "fa-own-"));
    if (existing !== undefined) await writeFile(join(dir, path), existing);
    const said: string[] = [];
    const spy = vi.spyOn(console, "error").mockImplementation((m: unknown) => said.push(String(m)));
    try {
      await applyArtifactPlan(await planArtifacts(dir, [{ path, content: generated }], force, DOCKER_TARGET));
    } finally {
      spy.mockRestore();
    }
    return { content: await readFile(join(dir, path), "utf8"), said: said.join("\n") };
  }

  it("a file fastagent did NOT generate survives --force", async () => {
    for (const path of PATHS) {
      const mine = "hand written, no marker\n";
      const r = await attempt(path, mine, true);
      expect(r.content, path).toBe(mine);
      expect(r.said, path).toMatch(/not generated by fastagent/);
    }
  });

  it("ours is kept without --force and regenerated with it", async () => {
    const edited = `${MARKER}\nedited by me\n`;
    const kept = await attempt("Dockerfile", edited, false);
    expect(kept.content).toBe(edited);
    expect(kept.said).toMatch(/no longer matches what fastagent deploy init docker would generate; pass --force/);

    const forced = await attempt("Dockerfile", edited, true);
    expect(forced.content).toBe(generated);
    expect(forced.said).toMatch(/wrote Dockerfile/);
  });
});
