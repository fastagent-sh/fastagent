/**
 * The ownership rule that decides what `deploy` may overwrite: a file fastagent generated carries a
 * marker and is refreshed under `--force`; a file it did not is never touched, whatever the flag says.
 *
 * It lives here rather than in the CLI e2e suite because it is a small state machine over
 * (exists, ours, force, alwaysWrite) — command LOGIC, which vitest.config.ts reserves this project's subprocess
 * tests against. Proving it by spawning `deploy` eight times made it the slowest test in the suite and
 * the only reliably flaky one (eight cold starts against a 30s ceiling, under file-parallel load). The
 * CLI keeps ONE spawn, for the wiring.
 */
import { mkdtemp, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { tmpdir } from "node:os";
import { describe, expect, it, vi } from "vitest";
import { HOSTS, applyArtifactPlan, planArtifacts } from "../src/cli/commands/deploy.ts";
import type { DeployHost } from "../src/deploy/hosts.ts";

/** Each artifact kind: the opening bytes that make it OURS, and WHO answers for it. A host answers
 *  only its own kind; "container" is the pair `planArtifacts` answers itself, for every host. */
const MARKERS = {
  "fastagent/Dockerfile": { marker: "# Generated by `fastagent deploy`", owner: "container" },
  ".dockerignore": { marker: "# Generated by `fastagent deploy`", owner: "container" },
  "fastagent/fastagent.bot.compose.yml": { marker: "# Generated by `fastagent deploy docker`", owner: "docker" },
  "fastagent/fly.bot.toml": { marker: "# Generated by `fastagent deploy fly`", owner: "fly" },
  "fastagent/agentcore.bot.template.yaml": {
    marker: "# Generated by `fastagent deploy agentcore`",
    owner: "agentcore",
  },
} as const satisfies Record<string, { marker: string; owner: DeployHost | "container" }>;
type Kind = keyof typeof MARKERS;

/** What the dispatcher binds for the host being deployed — ONE host's predicate, never a union over
 *  all of them: the union is what a misrouted or missing predicate would hide, since it answers for
 *  every kind whoever is deploying. The container's two get a predicate that claims nothing, which is
 *  the claim: `planArtifacts` owns them whatever the host says. */
const isOursFor = (path: Kind): ((p: string, c: string) => boolean) => {
  const { owner } = MARKERS[path];
  return owner === "container" ? () => false : HOSTS[owner].isOurs;
};

/** Generated content for `path`: the marker must OPEN the file, which is the rule being tested. */
const generatedFor = (path: Kind): string => `${MARKERS[path].marker}\nfresh\n`;

/** Run one write against a fresh dir seeded with `existing`, capturing what the command said. */
async function attempt(
  path: Kind,
  existing: string | undefined,
  force: boolean,
): Promise<{ content: string; said: string; stale: string[] }> {
  const dir = await mkdtemp(join(tmpdir(), "fa-own-"));
  if (existing !== undefined) {
    await mkdir(dirname(join(dir, path)), { recursive: true });
    await writeFile(join(dir, path), existing);
  }
  const said: string[] = [];
  const spy = vi.spyOn(console, "error").mockImplementation((m: unknown) => said.push(String(m)));
  let stale: string[];
  try {
    const plan = await planArtifacts(dir, [{ path, content: generatedFor(path) }], { force, isOurs: isOursFor(path) });
    stale = plan.stale;
    await applyArtifactPlan(plan);
  } finally {
    spy.mockRestore();
  }
  return { content: await readFile(join(dir, path), "utf8"), said: said.join("\n"), stale };
}

describe("deploy: ownership decides what --force may replace", () => {
  it("a file fastagent did NOT generate survives --force — every artifact kind", async () => {
    // The table must know every kind: one missing reads as the author's forever, which silently turns
    // --force into a no-op for it (`fly.toml` was exactly that bug).
    for (const path of Object.keys(MARKERS) as Kind[]) {
      const mine = "hand written, no marker\n";
      const r = await attempt(path, mine, true);
      expect(r.content, path).toBe(mine);
      expect(r.said, path).toMatch(/not generated by fastagent/);
    }
  });

  it("ours is kept without --force and regenerated with it", async () => {
    const path = "fastagent/Dockerfile";
    const stale = `${MARKERS[path].marker}\nedited by me\n`;

    const kept = await attempt(path, stale, false);
    expect(kept.content).toBe(stale); // the edit survives
    expect(kept.said).toMatch(/no longer matches what deploy would generate/); // …and names --force
    // REPORTED as stale, so the caller can decide: `--run` would deploy FROM this file, which is a determinate
    // mismatch between what ships and what the definition says.
    expect(kept.stale).toEqual([path]);

    const forced = await attempt(path, stale, true);
    expect(forced.content).toBe(generatedFor(path));
    expect(forced.said).toMatch(/wrote fastagent\/Dockerfile/);
    expect(forced.stale).toEqual([]); // regenerated, so nothing to decide about

    // A file we did NOT generate is never stale: `--force` does not touch it either, and taking a path back is
    // what deleting the marker line is for.
    expect((await attempt(path, "FROM node:22-slim\n", false)).stale).toEqual([]);
  });
});
