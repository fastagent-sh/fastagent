import { describe, expect, it } from "vitest";
import { mkdir, mkdtemp, realpath, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { agentWorkspace, runInProcess, withRepoModules } from "./cli-run.ts";

describe("cli: login and models", () => {
  it("login OUTSIDE an agent announces the global credential — the scope switch is never silent", async () => {
    // Every other command refuses a non-agent dir; login has the one legitimate fallback (there is no
    // project credential to write). It must SAY so: the global file is not what dev/start in a real
    // agent would read, so a silent switch would strand the credential invisibly.
    const home = await mkdtemp(join(tmpdir(), "fa-login-global-home-"));
    const cwd = await mkdtemp(join(tmpdir(), "fa-login-global-"));
    const env: NodeJS.ProcessEnv = { ...process.env, HOME: home };
    delete env.FASTAGENT_AUTH_PATH;
    const { code, stderr } = await runInProcess(["login", "no-such-provider"], cwd, env);
    expect(code).not.toBe(0);
    // The marker names itself, at both positions the lookup checks.
    expect(stderr).toMatch(/no agent here \(no fastagent\.config\.ts\)/);
    await expect(stat(join(cwd, ".secrets"))).rejects.toThrow(); // nothing created in the non-agent dir

    // …and it is silent when FASTAGENT_AUTH_PATH outranks the fallback: an announcement naming a file the
    // run does not write would be worse than none.
    const directed = await runInProcess(["login", "no-such-provider"], cwd, {
      ...env,
      FASTAGENT_AUTH_PATH: join(cwd, "auth.json"),
    });
    expect(directed.stderr).not.toMatch(/logging in GLOBALLY/);

    // Standing INSIDE an agent is NOT "outside an agent" — findAgentDir refuses that position with
    // its own way out, and login must tell the same story as every other command instead of quietly
    // switching scope.
    const inside = join(cwd, "agent", "tools");
    await mkdir(inside, { recursive: true });
    await writeFile(join(cwd, "agent", "fastagent.config.ts"), "export default {};\n");
    const nested = await runInProcess(["login", "no-such-provider"], inside, env);
    expect(nested.stderr).toMatch(/is inside the agent .* — run from/);
    expect(nested.stderr).not.toMatch(/logging in GLOBALLY/);
  });

  it("login --deployment needs the host named: one host's file in the dir is never taken as the answer", async () => {
    // A Railway deploy leaves no file of its own, so a dir holding a fly manifest may have been deployed to Railway since.
    const dir = await agentWorkspace("fa-login-deployment-", {
      "fly.agent.toml": "# Generated by `fastagent deploy fly`\n",
    });
    const bare = await runInProcess(["login", "--no-input", "--deployment"], dir);
    expect([bare.code, bare.stderr]).toEqual([2, expect.stringMatching(/--deployment <host>.*argument missing/)]);
    const wrong = await runInProcess(["login", "--deployment", "heroku", "--no-input"], dir);
    expect([wrong.code, wrong.stderr]).toEqual([2, expect.stringMatching(/--deployment takes a host \(docker, fly/)]);
    // A ticket's check is not a new sign-in on the box, which would replace the one the person is at.
    const checking = await runInProcess(
      ["login", "openai", "--deployment", "fly", "--check", "0123456789abcdef", "--json"],
      dir,
    );
    expect([checking.code, checking.stderr]).toEqual([2, expect.stringContaining("without --deployment")]);
  });

  it("login --deployment without a terminal names the commands it prints with the host account's --env-file", async () => {
    const dir = await agentWorkspace("fa-login-envfile-");
    const env = join(dir, "account.env");
    await writeFile(env, "AWS_REGION=eu-west-1\n");
    const named = await runInProcess(["login", "--deployment", "agentcore", "--env-file", env, "--json"], dir);
    expect(named.code).toBe(2);
    const choices = JSON.parse(named.stdout);
    expect(choices.choices).toContainEqual(
      expect.objectContaining({
        provider: "openai",
        method: "account",
        command: `fastagent login openai --method account --deployment agentcore --env-file ${env} --json`,
      }),
    );
    // Only for a deployment: the file is the host account's, and a local login has none.
    const local = await runInProcess(["login", "openai", "--env-file", env, "--no-input"], dir);
    expect([local.code, local.stderr]).toEqual([2, expect.stringContaining("pass --deployment <host> too")]);
  });

  it("login --config names the deployment --deployment logs in: without it the flag is refused, not ignored", async () => {
    const dir = await agentWorkspace("fa-login-config-");
    const refused = await runInProcess(["login", "openai", "--config", "acme.json", "--no-input"], dir);
    expect([refused.code, refused.stderr]).toEqual([
      2,
      expect.stringContaining("--config names the deployment that --deployment logs in: pass --deployment <host> too"),
    ]);
    expect(refused.stderr).not.toMatch(/GLOBALLY/);
  });

  it("login --deployment without a terminal: a choice names the deployment, a key travels with the next deploy", async () => {
    const dir = await agentWorkspace("fa-login-deployment-agent-");
    const unnamed = await runInProcess(["login", "--deployment", "fly", "--json"], dir);
    expect(unnamed.code).toBe(2);
    const choices = JSON.parse(unnamed.stdout);
    expect(choices.status).toBe("need_choice");
    expect(choices.choices).toContainEqual(
      expect.objectContaining({
        provider: "openai",
        method: "account",
        command: "fastagent login openai --method account --deployment fly --json",
      }),
    );
    // What authenticates a provider on THIS machine says nothing of the box.
    expect(choices.choices.every((choice: object) => !("status" in choice))).toBe(true);

    const key = await runInProcess(["login", "openai", "--method", "api-key", "--deployment", "fly", "--json"], dir);
    expect(key.code).toBe(0);
    expect(JSON.parse(key.stdout)).toMatchObject({
      status: "need_user_action",
      deployment: "fly",
      variables: ["OPENAI_API_KEY"],
      set_command: "fastagent secrets set fly OPENAI_API_KEY",
      check_command: "fastagent deploy fly --run",
      agent_next_steps: expect.stringContaining("themselves: not in this conversation"),
    });
    expect(JSON.parse(key.stdout)).not.toHaveProperty("value_file");
    // Docker holds no values of its own: Compose takes the key from the environment that runs it.
    const docker = await runInProcess(
      ["login", "openai", "--method", "api-key", "--deployment", "docker", "--json"],
      dir,
    );
    const said = JSON.parse(docker.stdout);
    expect(said).toMatchObject({ status: "need_user_action", deployment: "docker", variables: ["OPENAI_API_KEY"] });
    expect(said).not.toHaveProperty("set_command");
    expect(said.agent_next_steps).toContain("in the environment that runs Compose");
  });

  it("models inside an agent's subdirectory refuses, instead of listing what another agent's providers offer", async () => {
    // As for login, standing inside an agent must not count as standing outside one: the list outside an agent
    // leaves out the providers the agent's configuration declares.
    const home = await mkdtemp(join(tmpdir(), "fa-models-home-"));
    const workspace = await mkdtemp(join(tmpdir(), "fa-models-nested-"));
    const inside = join(workspace, "agent", "src");
    await mkdir(inside, { recursive: true });
    await writeFile(join(workspace, "agent", "fastagent.config.ts"), "export default {};\n");
    const listed = await runInProcess(["models", "claude"], inside, { ...process.env, HOME: home });
    expect(listed.code).toBe(1);
    expect(listed.stderr).toMatch(/is inside the agent .* — run from/);
  });

  it("models in an agent lists its definition's providers, without the secrets a serve needs", async () => {
    // A secret not filled in yet (`add telegram` writes none) stops dev and start; listing models must not need it.
    const dir = await agentWorkspace("fa-models-shape-", {
      "fastagent.config.ts":
        'import { fauxProvider } from "@earendil-works/pi-ai";\n' +
        "export default { providers: [{\n" +
        '  kind: "fastagent.needs", secrets: [{ name: "FA_TEST_GATEWAY_KEY", optional: false }],\n' +
        '  build: () => fauxProvider({ provider: "gw", models: [{ id: "m1" }] }).provider,\n' +
        "}] };\n",
    });
    await withRepoModules(dir);
    const env: NodeJS.ProcessEnv = { ...process.env };
    delete env.FA_TEST_GATEWAY_KEY;
    const listed = await runInProcess(["models", "gw/"], dir, env);
    expect([listed.code, listed.stdout.trim()], listed.stderr).toEqual([0, "gw/m1"]);
    const json = await runInProcess(["models", "gw/", "--json"], dir, env);
    expect(JSON.parse(json.stdout)).toEqual([{ spec: "gw/m1", provider: "gw", id: "m1", name: "m1" }]);
  });

  it("FASTAGENT_AUTH_PATH at the user-global credential is the documented sharing path, not a leak", async () => {
    // `FASTAGENT_AUTH_PATH=~/.fastagent/.secrets/auth.json` from inside an agent is how docs/cli.md says to
    // pin every agent to one account. Warning about it would be advice against our own documentation:
    // that directory is fastagent's own machinery home and needs no .gitignore.
    const home = await mkdtemp(join(tmpdir(), "fa-share-home-"));
    const cwd = await agentWorkspace("fa-share-agent-");
    const env: NodeJS.ProcessEnv = { ...process.env, HOME: home };
    delete env.FASTAGENT_AUTH_PATH;
    const shared = join(home, ".fastagent", ".secrets", "auth.json");
    const { stderr } = await runInProcess(["login", "no-such-provider"], cwd, { ...env, FASTAGENT_AUTH_PATH: shared });
    expect(stderr).not.toMatch(/cannot be committed/);
  });

  it("without a terminal, a choice not given is answered with the choices and a command for each (exit 2)", async () => {
    // runInProcess() pipes stdio, as a coding agent's shell does.
    const cwd = await agentWorkspace("fa-login-agent-");
    const unnamed = await runInProcess(["login"], cwd);
    expect(unnamed.code).toBe(2);
    expect(unnamed.stderr).toMatch(/name the provider to sign in to \(one of .*openai-codex.*\)/);
    const both = await runInProcess(["login", "OpenAI", "--json"], cwd);
    expect(both.code).toBe(2);
    expect(JSON.parse(both.stdout)).toMatchObject({
      status: "need_choice",
      message: "OpenAI signs in with an account or an API key: pass --method account or --method api-key",
      choices: [
        {
          provider: "openai",
          method: "account",
          label: "Sign in with ChatGPT",
          command: "fastagent login openai --method account --json",
        },
        { provider: "openai", method: "api-key", command: "fastagent login openai --method api-key --json" },
      ],
      agent_next_steps: expect.stringContaining("Ask the user which"),
    });
    expect((await runInProcess(["login", "openai", "--method", "key"], cwd)).stderr).toMatch(
      /--method must be account or api-key/,
    );
  });

  it("without a terminal, an API key is the person's to set where the agent reads it, never handed through", async () => {
    const cwd = await realpath(await agentWorkspace("fa-login-key-"));
    const env: NodeJS.ProcessEnv = { ...process.env, OPENAI_API_KEY: "" };
    const needed = await runInProcess(["login", "openai", "--method", "api-key", "--json"], cwd, env);
    expect([needed.code, JSON.parse(needed.stdout)]).toEqual([
      0,
      {
        status: "need_user_action",
        provider: "openai",
        method: "api-key",
        variables: ["OPENAI_API_KEY"],
        value_file: join(cwd, ".secrets", ".env"),
        check_command: "fastagent auth check --provider openai --json",
        agent_next_steps:
          `Ask the user to set OPENAI_API_KEY=<their OpenAI key> in ${join(cwd, ".secrets", ".env")} themselves, ` +
          "not in this conversation. Once they say they have, run check_command.",
      },
    ]);
    // An account sign-in stored for the provider outranks a key in the environment: it goes first, or the key is unused.
    const authFile = join(cwd, ".secrets", "auth.json");
    const oauth = { type: "oauth", access: "a", refresh: "r", expires: Date.now() + 3_600_000 };
    await writeFile(authFile, JSON.stringify({ openai: oauth }));
    const outranked = JSON.parse(
      (await runInProcess(["login", "openai", "--method", "api-key", "--json"], cwd, env)).stdout,
    );
    expect(outranked).toMatchObject({
      status: "need_user_action",
      logout_command: "fastagent logout openai",
      agent_next_steps: expect.stringContaining(
        `OpenAI is signed in with an account in ${authFile}, which outranks a key in the environment`,
      ),
    });
    await writeFile(authFile, "{}\n");

    // With no agent's value file to name, the person signs in at a terminal of their own, into the file `-g` reads:
    // a variable set now would never reach the agent's environment, fixed when it started.
    const outside = await mkdtemp(join(tmpdir(), "fa-login-key-outside-"));
    const global = await runInProcess(["login", "openai", "--method", "api-key", "--json"], outside, {
      ...env,
      HOME: outside,
    });
    expect(JSON.parse(global.stdout)).toMatchObject({
      status: "need_user_action",
      terminal_command: "fastagent login openai --method api-key -g",
      check_command: "fastagent auth check --provider openai -g --json",
    });

    const ready = await runInProcess(["login", "openai", "--method", "api-key", "--json"], cwd, {
      ...env,
      OPENAI_API_KEY: "sk-x",
    });
    expect(JSON.parse(ready.stdout)).toEqual({
      status: "ready",
      provider: "openai",
      method: "api-key",
      source: "OPENAI_API_KEY",
    });
  });

  it("login from $HOME does NOT self-ignore the HOME-global ~/.fastagent (a dotfiles repo may track it)", async () => {
    // self-ignore protects agent PROJECT trees, not the user's home. Run from $HOME (cwd == home) so
    // the credential default IS the global file; the bogus provider fails after the self-ignore
    // decision, so an absent .gitignore proves the global dir was left alone.
    // NOT realpath'd on purpose: macOS hands the child a /var→/private/var symlinked $HOME, so this
    // also exercises that the home check canonicalizes (a raw string compare would leak a .gitignore here).
    const home = await mkdtemp(join(tmpdir(), "fa-home-"));
    const env: NodeJS.ProcessEnv = { ...process.env, HOME: home };
    delete env.FASTAGENT_AUTH_PATH;
    const { code } = await runInProcess(["login", "no-such-provider"], home, env);
    expect(code).not.toBe(0);
    await expect(stat(join(home, ".fastagent", ".gitignore"))).rejects.toThrow(); // home left untouched
  });

  it("login reads the workspace .secrets/.env (a FASTAGENT_AUTH_PATH set there takes effect)", async () => {
    // Regression: login used to load .env from ./<provider> (the positional is the provider, not a dir).
    // Put FASTAGENT_AUTH_PATH in .secrets/.env (the workspace .env home) pointing OUTSIDE the tree — if
    // it is honored, auth resolves there and the secrets dir is never self-ignored; if the bug returns
    // (.env ignored), auth falls back in-tree and .secrets/.gitignore appears. Its ABSENCE is the proof.
    const cwd = await mkdtemp(join(tmpdir(), "fa-login-env-"));
    const external = join(await mkdtemp(join(tmpdir(), "fa-ext-")), "auth.json");
    await mkdir(join(cwd, ".secrets"), { recursive: true });
    await writeFile(join(cwd, ".secrets", ".env"), `FASTAGENT_AUTH_PATH=${external}\n`);
    const env: NodeJS.ProcessEnv = { ...process.env };
    delete env.FASTAGENT_AUTH_PATH; // must come only from .env
    const { code } = await runInProcess(["login", "no-such-provider"], cwd, env);
    expect(code).not.toBe(0);
    await expect(stat(join(cwd, ".secrets", ".gitignore"))).rejects.toThrow(); // external path won → no in-tree self-ignore
  });
});
